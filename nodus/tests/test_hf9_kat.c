typedef struct { uint8_t d[64]; uint8_t *rlp; size_t n; } mnode_t;
typedef struct { mnode_t *v; size_t n, cap; } mstore_t;

static int ms_get(void *ctx, const uint8_t dg[64], uint8_t **rlp,
                  size_t *len) {
    mstore_t *s = ctx;
    for (size_t i = 0; i < s->n; i++) {
        if (memcmp(s->v[i].d, dg, 64) == 0) {
            uint8_t *c = malloc(s->v[i].n);
            if (!c) return -2;
            memcpy(c, s->v[i].rlp, s->v[i].n);
            *rlp = c;
            *len = s->v[i].n;
            return 0;
        }
    }
    return 1;
}

static int ms_put(void *ctx, const uint8_t dg[64], const uint8_t *rlp,
                  size_t len) {
    mstore_t *s = ctx;
    for (size_t i = 0; i < s->n; i++)
        if (memcmp(s->v[i].d, dg, 64) == 0)
            return (s->v[i].n == len && memcmp(s->v[i].rlp, rlp, len) == 0)
                       ? 0 : -2;
    if (s->n == s->cap) {
        size_t nc = s->cap ? s->cap * 2 : 64;
        mnode_t *nv = realloc(s->v, nc * sizeof(*nv));
        if (!nv) return -2;
        s->v = nv;
        s->cap = nc;
    }
    s->v[s->n].rlp = malloc(len);
    if (!s->v[s->n].rlp) return -2;
    memcpy(s->v[s->n].rlp, rlp, len);
    memcpy(s->v[s->n].d, dg, 64);
    s->v[s->n].n = len;
    s->n++;
    return 0;
}

static void ms_free(mstore_t *s) {
    for (size_t i = 0; i < s->n; i++) free(s->v[i].rlp);
    free(s->v);
    memset(s, 0, sizeof(*s));
}

typedef struct {
    const uint8_t *key;
    size_t         klen;
    const uint8_t *val;       /* 64 bytes */
} item_t;

/* incremental trie over `n` items in the given order into a fresh store;
 * the root (and, on request, a copy of the root node RLP) come out.
 * 0 / -1. */
static int mem_root(const item_t *it, size_t n, int reverse,
                    uint8_t root[64], uint8_t **root_rlp, size_t *root_len) {
    mstore_t ms;
    memset(&ms, 0, sizeof(ms));
    evm_trie_store_t st = { &ms, ms_get, ms_put };
    uint8_t empty[64];
    evm_trie_t *t = NULL;
    int rc = -1;
    if (evm_trie_empty_root(empty) == 0 &&
        evm_trie_open(&st, empty, &t) == 0) {
        int ok = 1;
        for (size_t i = 0; ok && i < n; i++) {
            const item_t *x = &it[reverse ? n - 1 - i : i];
            ok = evm_trie_set(t, x->key, x->klen, x->val, 64) == 0;
        }
        if (ok && evm_trie_commit(t, root) == 0) {
            rc = 0;
            if (root_rlp) {
                *root_rlp = NULL;
                *root_len = 0;
                if (memcmp(root, empty, 64) != 0)
                    rc = ms_get(&ms, root, root_rlp, root_len) == 0 ? 0 : -1;
            }
        }
    }
    evm_trie_close(t);
    ms_free(&ms);
    return rc;
}

static int full_root(const item_t *it, size_t n, uint8_t root[64]) {
    evm_trie_full_kv *kv = n ? malloc(n * sizeof(*kv)) : NULL;
    if (n && !kv) return -1;
    for (size_t i = 0; i < n; i++) {
        kv[i].key = it[i].key;
        kv[i].key_len = it[i].klen;
        kv[i].val = it[i].val;
        kv[i].val_len = 64;
    }
    int rc = evm_trie_full_root(kv, n, 1, EVM_TRIE_FULL_SHA3_512, root);
    free(kv);
    return rc == 0 ? 0 : -1;
}

/* the kind of a root node RLP: "leaf", "extension" or "branch" (the
 * structural reading of the encoding: a 17-item list = branch; a 2-item
 * list whose first item is the hex-prefix path: flag nibble 0/1 =
 * extension, 2/3 = leaf) */
/* RLP item header at r[p]: payload offset and length; 0 / -1 */
static int rlp_hdr(const uint8_t *r, size_t n, size_t p, size_t *poff,
                   size_t *plen, int *is_list) {
    if (p >= n) return -1;
    uint8_t b = r[p];
    size_t ll;
    *is_list = b >= 0xc0;
    if (b < 0x80) { *poff = p; *plen = 1; return 0; }
    if (b <= 0xb7) { *poff = p + 1; *plen = b - 0x80u; return 0; }
    if (b <= 0xbf) ll = b - 0xb7u;
    else if (b <= 0xf7) { *poff = p + 1; *plen = b - 0xc0u; return 0; }
    else ll = b - 0xf7u;
    if (p + 1 + ll > n) return -1;
    size_t L = 0;
    for (size_t i = 0; i < ll; i++) L = (L << 8) | r[p + 1 + i];
    *poff = p + 1 + ll;
    *plen = L;
    return 0;
}

static const char *node_kind(const uint8_t *r, size_t n) {
    size_t off, len;
    int lst;
    if (rlp_hdr(r, n, 0, &off, &len, &lst) != 0 || !lst || off + len != n)
        return "?";
    size_t p = off, items = 0, first_off = 0, first_len = 0;
    while (p < n) {
        size_t io, il;
        int il_list;
        if (rlp_hdr(r, n, p, &io, &il, &il_list) != 0) return "?";
        if (items == 0) { first_off = io; first_len = il; }
        items++;
        p = io + il;
    }
    if (p != n) return "?";
    if (items == 17) return "branch";
    if (items == 2 && first_len > 0) {
        int flag = r[first_off] >> 4;       /* hex-prefix flag nibble */
        if (flag == 0 || flag == 1) return "extension";
        if (flag == 2 || flag == 3) return "leaf";
    }
    return "?";
}

/* ── file hash ──────────────────────────────────────────────────────── */

static int file_sha256_hex(const char *path, char out[65]) {
    FILE *f = fopen(path, "rb");
    if (!f) return -1;
    EVP_MD_CTX *c = EVP_MD_CTX_new();
    if (!c || EVP_DigestInit_ex(c, EVP_sha256(), NULL) != 1) {
        fclose(f);
        if (c) EVP_MD_CTX_free(c);
        return -1;
    }
    uint8_t buf[8192];
    size_t n;
    while ((n = fread(buf, 1, sizeof(buf), f)) > 0)
        if (EVP_DigestUpdate(c, buf, n) != 1) {
            fclose(f);
            EVP_MD_CTX_free(c);
            return -1;
        }
    int bad = ferror(f);
    fclose(f);
    uint8_t md[32];
    unsigned ml = 0;
    int ok = !bad && EVP_DigestFinal_ex(c, md, &ml) == 1 && ml == 32;
    EVP_MD_CTX_free(c);
    if (!ok) return -1;
    for (int i = 0; i < 32; i++) snprintf(out + 2 * i, 3, "%02x", md[i]);
    return 0;
}

