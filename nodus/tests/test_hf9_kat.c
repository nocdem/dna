typedef struct {
    int            kind;      /* 0 blob, 1 int64, 2 text */
    const uint8_t *p;
    size_t         n;
    int64_t        i;
} arg_t;

/* INSERT with bound arguments; every bind result is checked */
static int insert_row(sqlite3 *db, const char *sql, const arg_t *a,
                      int na) {
    sqlite3_stmt *st = NULL;
    if (sqlite3_prepare_v2(db, sql, -1, &st, NULL) != SQLITE_OK) return -1;
    int ok = 1;
    for (int i = 0; ok && i < na; i++) {
        int rc;
        if (a[i].kind == 0)
            rc = sqlite3_bind_blob(st, i + 1, a[i].p, (int)a[i].n,
                                   SQLITE_STATIC);
        else if (a[i].kind == 1)
            rc = sqlite3_bind_int64(st, i + 1, a[i].i);
        else
            rc = sqlite3_bind_text(st, i + 1, (const char *)a[i].p,
                                   (int)a[i].n, SQLITE_STATIC);
        ok = rc == SQLITE_OK;
    }
    ok = ok && sqlite3_step(st) == SQLITE_DONE;
    sqlite3_finalize(st);
    return ok ? 0 : -1;
}

/* ── one leg vector ─────────────────────────────────────────────────── */

typedef struct {
    uint8_t  key[64];
    size_t   klen;
    uint8_t  val[64];
} leg_out_t;

/* the production leaf value and the key of the leg's record, from the
 * record's fields (never from the JSON's value / path / key) */
static int leg_compute(int leg, json_object *rec, leg_out_t *o,
                       uint8_t *token_hold /* 64, L1/L2 scratch */) {
    (void)token_hold;
    memset(o, 0, sizeof(*o));
    switch (leg) {
    case 1: {
        uint8_t nul[64], tok[64], txh[64], D[64], pre[65];
        uint64_t amount, oi, ub;
        const char *owner = jstr(rec, "owner");
        if (jhex(rec, "nullifier", nul, 64) || jhex(rec, "token_id", tok, 64) ||
            jhex(rec, "tx_hash", txh, 64) || jnum(rec, "amount", &amount) ||
            jnum(rec, "output_index", &oi) || jnum(rec, "unlock_block", &ub) ||
            !owner)
            return -1;
        if (nodus_witness_merkle_leaf_hash(nul, owner, amount, tok, txh,
                                           (uint32_t)oi, D, ub) != 0)
            return -1;
        pre[0] = 0x00;
        memcpy(pre + 1, D, 64);
        if (qgp_sha3_512(pre, sizeof(pre), o->val) != 0) return -1;
        memcpy(o->key, nul, 64);
        o->klen = 64;
        return 0;
    }
    case 2: {
        dna_v2_token_leaf_t L;
        uint64_t dec, flg;
        memset(&L, 0, sizeof(L));
        const char *nm = jstr(rec, "name"), *sy = jstr(rec, "symbol"),
                   *cf = jstr(rec, "creator_fp");
        if (!nm || !sy || !cf || jhex(rec, "token_id", L.token_id, 64) ||
            jnum(rec, "decimals", &dec) || jnum(rec, "flags", &flg) ||
            jnum(rec, "supply", &L.supply) ||
            jnum(rec, "block_height", &L.block_height))
            return -1;
        L.name = nm;        L.name_len = strlen(nm);
        L.symbol = sy;      L.symbol_len = strlen(sy);
        L.creator_fp = cf;  L.creator_fp_len = strlen(cf);
        L.decimals = (uint8_t)dec;
        L.flags = (uint8_t)flg;
        if (dna_v2_token_leaf_hash(&L, o->val) != 0) return -1;
        memcpy(o->key, L.token_id, 64);
        o->klen = 64;
        return 0;
    }
    case 3: {
        dna_claims_entry_t e;
        uint64_t dom;
        memset(&e, 0, sizeof(e));
        if (jhex(rec, "nullifier", e.nullifier, 64) ||
            jhex(rec, "manifest_hash", e.manifest_hash, 64) ||
            jnum(rec, "target_domain_id", &dom) ||
            jnum(rec, "leaf_index", &e.leaf_index) ||
            jnum(rec, "amount", &e.amount) ||
            jnum(rec, "claimed_height", &e.claimed_height))
            return -1;
        e.target_domain_id = (uint32_t)dom;
        if (dna_claims_leaf_hash(&e, o->val) != 0) return -1;
        memcpy(o->key, e.nullifier, 64);
        o->klen = 64;
        return 0;
    }
    case 4: {
        dna_v2_name_row_t r;
        memset(&r, 0, sizeof(r));
        const char *nm = jstr(rec, "name");
        if (!nm || strlen(nm) == 0 || strlen(nm) > DNA_V2_NAME_MAX_LEN ||
            jhex(rec, "owner", r.owner, 64) ||
            jnum(rec, "registered_height", &r.registered_height))
            return -1;
        r.name_len = (uint8_t)strlen(nm);
        memcpy(r.name, nm, r.name_len);
        if (dna_v2_name_leaf_hash(&r, o->val) != 0) return -1;
        memcpy(o->key, nm, r.name_len);          /* the name bytes, raw */
        o->klen = r.name_len;
        return 0;
    }
    case 5: {
        dna_v2_storage_node_row_t r;
        uint64_t st, fs;
        memset(&r, 0, sizeof(r));
        if (jhex(rec, "node_fp", r.node_fp, 64) ||
            jhex(rec, "payee_fp", r.payee_fp, 64) ||
            jnum(rec, "bond", &r.bond) || jnum(rec, "status", &st) ||
            jnum(rec, "registered_height", &r.registered_height) ||
            jnum(rec, "exit_height", &r.exit_height) ||
            jnum(rec, "fail_streak", &fs) ||
            jnum(rec, "grace_until", &r.grace_until))
            return -1;
        r.status = (uint8_t)st;
        r.fail_streak = (uint32_t)fs;
        if (dna_v2_storage_node_leaf_hash(&r, o->val) != 0) return -1;
        memcpy(o->key, r.node_fp, 64);
        o->klen = 64;
        return 0;
    }
    case 6: {
        uint64_t k, ph;
        uint8_t root[64];
        if (jnum(rec, "k", &k) || jnum(rec, "published_height", &ph) ||
            jhex(rec, "root_k_fixture", root, 64))
            return -1;
        if (dna_v2_segment_leaf_hash_v2(k, root, ph, o->val) != 0) return -1;
        be64(k, o->key);
        o->klen = 8;
        return 0;
    }
    case 7: {
        uint64_t ep;
        uint8_t h[64];
        if (jnum(rec, "epoch_start", &ep) || jhex(rec, "snapshot_hash", h, 64))
            return -1;
        if (dna_v2_vset_leaf_hash(ep, h, o->val) != 0) return -1;
        be64(ep, o->key);
        o->klen = 8;
        return 0;
    }
    case 8: {
        uint64_t ep;
        uint8_t dg[64];
        if (jnum(rec, "epoch_start", &ep) || jhex(rec, "digest", dg, 64))
            return -1;
        if (dna_v2_attendance_leaf_hash(ep, dg, o->val) != 0) return -1;
        be64(ep, o->key);
        o->klen = 8;
        return 0;
    }
    default:
        return -1;
    }
}

/* the record as one row of the scratch database (legs 1, 2, 3, 4, 7, 8) */
static int leg_insert(fx_t *fx, int leg, json_object *rec) {
    sqlite3 *db = fx->w->db;
    uint8_t b0[64], b1[64], b2[64], zero[64] = {0};
    uint64_t n0, n1, n2, n3;
    switch (leg) {
    case 1: {
        const char *owner = jstr(rec, "owner");
        if (jhex(rec, "nullifier", b0, 64) || jhex(rec, "token_id", b1, 64) ||
            jhex(rec, "tx_hash", b2, 64) || jnum(rec, "amount", &n0) ||
            jnum(rec, "output_index", &n1) || jnum(rec, "unlock_block", &n2) ||
            !owner)
            return -1;
        arg_t a[7] = {
            { 0, b0, 64, 0 }, { 2, (const uint8_t *)owner, strlen(owner), 0 },
            { 1, NULL, 0, (int64_t)n0 }, { 0, b1, 64, 0 }, { 0, b2, 64, 0 },
            { 1, NULL, 0, (int64_t)n1 }, { 1, NULL, 0, (int64_t)n2 } };
        return insert_row(db,
            "INSERT INTO utxo_set (nullifier, owner, amount, token_id, "
            "tx_hash, output_index, block_height, created_at, unlock_block, "
            "domain_id) VALUES (?1, ?2, ?3, ?4, ?5, ?6, 0, 0, ?7, 1)", a, 7);
    }
    case 2: {
        const char *nm = jstr(rec, "name"), *sy = jstr(rec, "symbol"),
                   *cf = jstr(rec, "creator_fp");
        if (!nm || !sy || !cf || jhex(rec, "token_id", b0, 64) ||
            jnum(rec, "decimals", &n0) || jnum(rec, "supply", &n1) ||
            jnum(rec, "flags", &n2) || jnum(rec, "block_height", &n3))
            return -1;
        arg_t a[8] = {
            { 0, b0, 64, 0 }, { 2, (const uint8_t *)nm, strlen(nm), 0 },
            { 2, (const uint8_t *)sy, strlen(sy), 0 },
            { 1, NULL, 0, (int64_t)n0 }, { 1, NULL, 0, (int64_t)n1 },
            { 2, (const uint8_t *)cf, strlen(cf), 0 },
            { 1, NULL, 0, (int64_t)n2 }, { 1, NULL, 0, (int64_t)n3 } };
        return insert_row(db,
            "INSERT INTO tokens (token_id, name, symbol, decimals, supply, "
            "creator_fp, flags, block_height, timestamp) VALUES (?1, ?2, "
            "?3, ?4, ?5, ?6, ?7, ?8, 0)", a, 8);
    }
    case 3: {
        if (jhex(rec, "nullifier", b0, 64) ||
            jhex(rec, "manifest_hash", b1, 64) ||
            jnum(rec, "target_domain_id", &n0) ||
            jnum(rec, "leaf_index", &n1) || jnum(rec, "amount", &n2) ||
            jnum(rec, "claimed_height", &n3))
            return -1;
        arg_t a[7] = {
            { 0, b0, 64, 0 }, { 0, b1, 64, 0 }, { 1, NULL, 0, (int64_t)n0 },
            { 0, zero, 64, 0 }, { 1, NULL, 0, (int64_t)n1 },
            { 1, NULL, 0, (int64_t)n2 }, { 1, NULL, 0, (int64_t)n3 } };
        return insert_row(db,
            "INSERT INTO v2_claims_spent (nullifier, manifest_hash, "
            "target_domain_id, target_asset_ref, leaf_index, amount, "
            "claimed_height, output_id) VALUES (?1, ?2, ?3, ?4, ?5, ?6, ?7, "
            "?4)", a, 7);
    }
    case 4: {
        const char *nm = jstr(rec, "name");
        if (!nm || jhex(rec, "owner", b0, 64) ||
            jnum(rec, "registered_height", &n0))
            return -1;
        arg_t a[3] = { { 0, (const uint8_t *)nm, strlen(nm), 0 },
                       { 0, b0, 64, 0 }, { 1, NULL, 0, (int64_t)n0 } };
        return insert_row(db,
            "INSERT INTO v2_names (name, owner, registered_height) VALUES "
            "(?1, ?2, ?3)", a, 3);
    }
    case 7: {
        static const uint8_t blob1[1] = { 0 };
        if (jnum(rec, "epoch_start", &n0) ||
            jhex(rec, "snapshot_hash", b0, 64))
            return -1;
        arg_t a[3] = { { 1, NULL, 0, (int64_t)n0 }, { 0, b0, 64, 0 },
                       { 0, blob1, 1, 0 } };
        return insert_row(db,
            "INSERT INTO validator_set_snapshots (epoch_start, "
            "active_count, snapshot_hash, snapshot_blob, "
            "created_at_height) VALUES (?1, 1, ?2, ?3, 1)", a, 3);
    }
    case 8: {
        if (jnum(rec, "epoch_start", &n0) || jhex(rec, "digest", b0, 64))
            return -1;
        arg_t a[2] = { { 1, NULL, 0, (int64_t)n0 }, { 0, b0, 64, 0 } };
        return insert_row(db,
            "INSERT INTO v2_attendance_epoch (epoch_start, digest) VALUES "
            "(?1, ?2)", a, 2);
    }
    default:
        return -1;
    }
}

static int check_leg_vector(fx_t *fx, json_object *v) {
    uint64_t legn = 0;
    json_object *lj = jget(v, "leg");
    CHECK(lj && json_object_is_type(lj, json_type_int), "leg is an integer");
    legn = (uint64_t)json_object_get_int64(lj);
    const int leg = (int)legn;
    CHECK(leg >= 1 && leg <= 8, "leg in 1..8");
    snprintf(g_ctx, sizeof(g_ctx), "leg_vectors leg %d (%s)", leg,
             jstr(v, "leg_name") ? jstr(v, "leg_name") : "?");
    json_object *rec = jget(v, "record");
    CHECK(rec != NULL, "record present");

    leg_out_t o;
    CHECK(leg_compute(leg, rec, &o, NULL) == 0,
          "the C computes key and value from the record");

    /* key bytes and path (A1 / F-2) */
    CHECK(jeq(v, "key", o.key, o.klen), "key bytes = the C's key");
    json_object *kl = jget(v, "key_len");
    CHECK(kl && (size_t)json_object_get_int64(kl) == o.klen, "key_len");
    uint8_t path[64];
    CHECK(qgp_sha3_512(o.key, o.klen, path) == 0 &&
          jeq(v, "path_sha3_512_of_key", path, 64),
          "path = SHA3-512(key), applied once");
    json_object *pn = jget(v, "path_nibbles");
    CHECK(pn && json_object_get_int64(pn) == 128, "path is 128 nibbles");

    /* the value, by the production leaf function */
    CHECK(jeq(v, "value", o.val, 64), "value = the production leaf value");
    if (leg != 1) {
        /* (L1's value_preimage is the 340-byte inner preimage: its value is
         * the OUTER hash, checked in the L1 block below) */
        size_t pl = 0;
        uint8_t *pre = unhex(jstr(v, "value_preimage"), &pl);
        uint8_t h[64];
        CHECK(pre && qgp_sha3_512(pre, pl, h) == 0 &&
              memcmp(h, o.val, 64) == 0,
              "control: SHA3-512(value_preimage) = the value");
        free(pre);
    }

    /* the single-leaf trie by the C primitives, in memory */
    item_t it = { o.key, o.klen, o.val };
    uint8_t root[64], froot[64];
    uint8_t *rrlp = NULL;
    size_t rlen = 0;
    CHECK(mem_root(&it, 1, 0, root, &rrlp, &rlen) == 0,
          "single-leaf root by evm_trie");
    json_object *slt = jget(v, "single_leaf_trie");
    CHECK(slt && jeq(slt, "root", root, 64), "single-leaf root");
    CHECK(slt && jeq(slt, "root_node_rlp", rrlp, rlen), "root-node RLP");
    json_object *rl = jget(slt, "root_node_rlp_len");
    CHECK(rl && (size_t)json_object_get_int64(rl) == rlen && rlen == 135,
          "root-node RLP is 135 bytes");
    free(rrlp);
    CHECK(full_root(&it, 1, froot) == 0 && memcmp(froot, root, 64) == 0,
          "evm_trie_full_root = the incremental root");

    /* L1: the 340-byte preimage, D and the outer hash (A2 / F-5) */
    if (leg == 1) {
        json_object *u = jget(v, "utxo");
        CHECK(u != NULL, "utxo block");
        uint8_t pre[340], nul[64], tok[64], txh[64], D[64], oi4[4];
        uint64_t amount, oi, ub;
        const char *owner = jstr(rec, "owner");
        CHECK(owner && strlen(owner) <= 128 && jhex(rec, "nullifier", nul, 64)
              == 0 && jhex(rec, "token_id", tok, 64) == 0 &&
              jhex(rec, "tx_hash", txh, 64) == 0 &&
              jnum(rec, "amount", &amount) == 0 &&
              jnum(rec, "output_index", &oi) == 0 &&
              jnum(rec, "unlock_block", &ub) == 0, "L1 record fields");
        memset(pre, 0, sizeof(pre));
        memcpy(pre, nul, 64);
        memcpy(pre + 64, owner, strlen(owner));      /* 128, NUL-padded */
        le64(amount, pre + 192);
        memcpy(pre + 200, tok, 64);
        memcpy(pre + 264, txh, 64);
        le32((uint32_t)oi, oi4);
        memcpy(pre + 328, oi4, 4);
        le64(ub, pre + 332);
        CHECK(jeq(u, "preimage340", pre, 340) && jeq(rec, "preimage340", pre,
              340), "the 340-byte preimage assembled here = the JSON's");
        CHECK(qgp_sha3_512(pre, 340, D) == 0 &&
              jeq(u, "inner_digest_D", D, 64) &&
              jeq(rec, "inner_digest_D", D, 64),
              "SHA3-512(preimage340) = D");
        uint8_t Dp[64];
        CHECK(nodus_witness_merkle_leaf_hash(nul, owner, amount, tok, txh,
                  (uint32_t)oi, Dp, ub) == 0 && memcmp(Dp, D, 64) == 0,
              "the production leaf-hash function gives D");
        uint8_t outer[65], ov[64];
        outer[0] = 0x00;
        memcpy(outer + 1, D, 64);
        CHECK(jeq(u, "outer_input", outer, 65), "outer input = 0x00 ‖ D");
        CHECK(qgp_sha3_512(outer, 65, ov) == 0 &&
              jeq(u, "trie_value_sha3_512_0x00_D", ov, 64) &&
              memcmp(ov, o.val, 64) == 0, "trie value = SHA3-512(0x00 ‖ D)");
        CHECK(memcmp(D, o.val, 64) != 0, "D is not the trie value");

        /* the short-owner variant: rebuilt from its 340 bytes */
        json_object *sv = jget(u, "short_owner_variant");
        CHECK(sv != NULL, "short-owner variant");
        size_t pl = 0;
        uint8_t *sp = unhex(jstr(sv, "preimage340"), &pl);
        CHECK(sp && pl == 340, "variant preimage length");
        const char *so = jstr(sv, "owner");
        CHECK(so && strlen(so) < 128, "variant owner");
        uint8_t ownbuf[128];
        memset(ownbuf, 0, sizeof(ownbuf));
        memcpy(ownbuf, so, strlen(so));
        CHECK(memcmp(sp + 64, ownbuf, 128) == 0 &&
              jeq(sv, "owner_bytes_128_nul_padded", ownbuf, 128),
              "variant owner is 128 NUL-padded bytes");
        uint64_t va = 0, vub = 0;
        for (int i = 7; i >= 0; i--) {
            va = (va << 8) | sp[192 + i];
            vub = (vub << 8) | sp[332 + i];
        }
        uint32_t voi = (uint32_t)sp[328] | (uint32_t)sp[329] << 8 |
                       (uint32_t)sp[330] << 16 | (uint32_t)sp[331] << 24;
        uint8_t vD[64], vpre[65], vval[64];
        CHECK(nodus_witness_merkle_leaf_hash(sp, so, va, sp + 200, sp + 264,
                  voi, vD, vub) == 0 && jeq(sv, "inner_digest_D", vD, 64),
              "variant: the production D");
        vpre[0] = 0;
        memcpy(vpre + 1, vD, 64);
        CHECK(qgp_sha3_512(vpre, 65, vval) == 0 &&
              jeq(sv, "trie_value", vval, 64),
              "variant: trie value = SHA3-512(0x00 ‖ D)");
        free(sp);
    }

    /* the production reader and build path (legs 1-4, 7, 8) */
    if (leg != 5 && leg != 6) {
        uint8_t inc[64], full[64];
        CHECK(leg_insert(fx, leg, rec) == 0, "the record as a database row");
        CHECK(nodus_witness_v2_trie_build_leg(fx->w, leg, inc, full) == 0,
              "build_leg from the row");
        CHECK(slt && jeq(slt, "root", inc, 64) && memcmp(inc, full, 64) == 0,
              "build_leg: incremental = full rebuild = the oracle's root");
    }
    return 0;
}

/* ── row sets ───────────────────────────────────────────────────────── */

static int check_row_set(int leg, json_object *s) {
    json_object *nj = jget(s, "n");
    json_object *rows = jget(s, "rows_sorted_by_key");
    CHECK(nj && rows && json_object_is_type(rows, json_type_array),
          "set shape");
    const size_t n = (size_t)json_object_array_length(rows);
    CHECK((size_t)json_object_get_int64(nj) == n, "n = number of rows");
    snprintf(g_ctx, sizeof(g_ctx), "leg_row_sets leg %d n=%zu", leg, n);

    uint8_t **keys = calloc(n ? n : 1, sizeof(*keys));
    uint8_t **vals = calloc(n ? n : 1, sizeof(*vals));
    size_t *klen = calloc(n ? n : 1, sizeof(*klen));
    item_t *items = calloc(n ? n : 1, sizeof(*items));
    CHECK(keys && vals && klen && items, "alloc");
    int rc = 0;
    for (size_t i = 0; i < n && !rc; i++) {
        json_object *r = json_object_array_get_idx(rows, (int)i);
        size_t vl = 0;
        keys[i] = unhex(jstr(r, "key"), &klen[i]);
        vals[i] = unhex(jstr(r, "value"), &vl);
        if (!keys[i] || !vals[i] || vl != 64 || klen[i] == 0) { rc = 1; break; }
        uint8_t path[64];
        if (qgp_sha3_512(keys[i], klen[i], path) != 0 ||
            !jeq(r, "path", path, 64)) { rc = 2; break; }
        if (i > 0) {
            size_t m = klen[i - 1] < klen[i] ? klen[i - 1] : klen[i];
            int c = memcmp(keys[i - 1], keys[i], m);
            if (c > 0 || (c == 0 && klen[i - 1] >= klen[i])) { rc = 3; break; }
        }
        items[i].key = keys[i];
        items[i].klen = klen[i];
        items[i].val = vals[i];
    }
    uint8_t asc[64], desc[64], full[64], empty[64];
    uint8_t *rrlp = NULL;
    size_t rlen = 0;
    int ok_roots = 0;
    if (!rc && mem_root(items, n, 0, asc, &rrlp, &rlen) == 0 &&
        mem_root(items, n, 1, desc, NULL, NULL) == 0 &&
        full_root(items, n, full) == 0)
        ok_roots = 1;
    const char *label = jstr(s, "root_node");
    int kind_ok = 0;
    if (ok_roots && label) {
        if (n == 0)
            kind_ok = strcmp(label, "empty") == 0 &&
                      evm_trie_empty_root(empty) == 0 &&
                      memcmp(asc, empty, 64) == 0;
        else
            kind_ok = strcmp(label, node_kind(rrlp, rlen)) == 0;
    }
    int roots_eq = ok_roots && jeq(s, "root", asc, 64) &&
                   memcmp(asc, desc, 64) == 0 && memcmp(asc, full, 64) == 0;
    for (size_t i = 0; i < n; i++) { free(keys[i]); free(vals[i]); }
    free(keys); free(vals); free(klen); free(items); free(rrlp);
    CHECK(rc == 0, "rows: decode, path = SHA3-512(key), strictly ascending");
    CHECK(ok_roots, "the C computes the roots");
    CHECK(roots_eq, "root: ascending = descending = full rebuild = oracle");
    CHECK(kind_ok, "root node kind = the oracle's label");
    return 0;
}

/* ── WP3: new_tags, compositions, votes ─────────────────────────────── */

#define T16 16

/* the tag text zero-padded to exactly 16 bytes */
static int tag16(const char *name, uint8_t out[T16]) {
    size_t n = strlen(name);
    if (n == 0 || n >= T16) return -1;
    memset(out, 0, T16);
    memcpy(out, name, n);
    return 0;
}

static int empty_root_c(uint8_t out[64]) {
    const uint8_t b = 0x80;
    return qgp_sha3_512(&b, 1, out);
}

typedef struct {
    const char *key;       /* the JSON key of the "..._all_trie_legs..." */
    const char *comp;      /* "CORE" / "SYS" / "STOR" in one_empty_leg   */
    const char *tag;       /* the composition tag text                   */
    size_t      nlegs;
    int         ntrie;     /* trie legs inside the composition           */
    int         trie_leg[4];  /* leg ids 1..8                            */
    int         trie_pos[4];  /* their positions in the composition      */
} comp_t;

static const comp_t COMPS[3] = {
    { "CORE_v4", "CORE", "NDS.CORE.v4", 7, 4, { 1, 2, 3, 4 },
      { 0, 1, 3, 4 } },
    { "SYS_v7", "SYS", "NDS.SYS.v7", 12, 2, { 7, 8, 0, 0 }, { 3, 6, 0, 0 } },
    { "STOR_v3", "STOR", "NDS.STOR.v3", 4, 2, { 5, 6, 0, 0 },
      { 0, 3, 0, 0 } }
};

/* the production composition of `ci` over legs[0..nlegs-1] */
static int compose_c(int ci, uint8_t legs[][64], uint8_t out[64]) {
    switch (ci) {
    case 0:
        return dna_v2_core_root_v4(legs[0], legs[1], legs[2], legs[3],
                                   legs[4], legs[5], legs[6], out);
    case 1:
        return dna_v2_system_root_v7(legs[0], legs[1], legs[2], legs[3],
                                     legs[4], legs[5], legs[6], legs[7],
                                     legs[8], legs[9], legs[10], legs[11],
                                     out);
    case 2:
        return dna_v2_storage_root_v3(legs[0], legs[1], legs[2], legs[3],
                                      out);
    }
    return -1;
}

/* this test's own restatement of the preimage: tag16 ‖ legs, SHA3-512 */
static int compose_own(const comp_t *c, uint8_t legs[][64], uint8_t out[64],
                       size_t *pre_len) {
    uint8_t pre[T16 + 12 * 64];
    if (tag16(c->tag, pre) != 0) return -1;
    for (size_t i = 0; i < c->nlegs; i++)
        memcpy(pre + T16 + i * 64, legs[i], 64);
    *pre_len = T16 + c->nlegs * 64;
    return qgp_sha3_512(pre, *pre_len, out);
}

/* the JSON "legs" array of an entry into legs[0..n-1]; 0 / -1 */
static int read_legs(json_object *e, size_t n, uint8_t legs[][64]) {
    json_object *a = jget(e, "legs");
    if (!a || !json_object_is_type(a, json_type_array) ||
        json_object_array_length(a) != n)
        return -1;
    for (size_t i = 0; i < n; i++) {
        size_t l = 0;
        const char *s = json_object_get_string(
            json_object_array_get_idx(a, i));
        uint8_t *b = unhex(s, &l);
        if (!b || l != 64) { free(b); return -1; }
        memcpy(legs[i], b, 64);
        free(b);
    }
    return 0;
}

/* one composition entry: the C function, the independent restatement and
 * the JSON root agree; `has_pre` entries also carry the preimage length and
 * the tag bytes */
static int check_comp_entry(json_object *e, int ci) {
    const comp_t *c = &COMPS[ci];
    uint8_t legs[12][64], got[64], own[64], tg[T16];
    size_t plen = 0;
    CHECK(read_legs(e, c->nlegs, legs) == 0, "composition legs decode");
    CHECK(compose_c(ci, legs, got) == 0, "the C composition runs");
    CHECK(jeq(e, "root", got, 64),
          "the C composition over the JSON legs == the oracle root");
    CHECK(compose_own(c, legs, own, &plen) == 0 &&
          memcmp(own, got, 64) == 0,
          "SHA3-512(tag ‖ legs) assembled here == the C composition (the "
          "C uses the oracle's tag)");
    json_object *pl = jget(e, "preimage_len");
    if (pl)
        CHECK(json_object_get_int64(pl) == (int64_t)plen,
              "the preimage length (464 / 784 / 272)");
    if (jget(e, "tag")) {
        CHECK(tag16(c->tag, tg) == 0 && jeq(e, "tag", tg, T16),
              "the JSON tag == the zero-padded ASCII name");
    }
    return 0;
}

