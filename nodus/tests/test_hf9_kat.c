/* ── hex and JSON helpers ──────────────────────────────────────────── */

static int nib(char c) {
    if (c >= '0' && c <= '9') return c - '0';
    if (c >= 'a' && c <= 'f') return c - 'a' + 10;
    return -1;
}

/* lowercase hex -> malloc'd bytes; NULL on a bad digit or odd length */
static uint8_t *unhex(const char *h, size_t *len) {
    if (!h) return NULL;
    size_t n = strlen(h);
    if (n % 2) return NULL;
    uint8_t *o = malloc(n / 2 ? n / 2 : 1);
    if (!o) return NULL;
    for (size_t i = 0; i < n / 2; i++) {
        int a = nib(h[2 * i]), b = nib(h[2 * i + 1]);
        if (a < 0 || b < 0) { free(o); return NULL; }
        o[i] = (uint8_t)(a << 4 | b);
    }
    *len = n / 2;
    return o;
}

static json_object *jget(json_object *o, const char *k) {
    json_object *r = NULL;
    if (!o || !json_object_object_get_ex(o, k, &r)) return NULL;
    return r;
}

static const char *jstr(json_object *o, const char *k) {
    json_object *v = jget(o, k);
    return (v && json_object_is_type(v, json_type_string))
               ? json_object_get_string(v) : NULL;
}

/* a record integer: a decimal string (the oracle's convention) */
static int jnum(json_object *o, const char *k, uint64_t *out) {
    const char *s = jstr(o, k);
    if (!s || !*s) return -1;
    char *e = NULL;
    *out = strtoull(s, &e, 10);
    return (e && !*e) ? 0 : -1;
}

/* a hex field of exactly n bytes into buf; 0 / -1 */
static int jhex(json_object *o, const char *k, uint8_t *buf, size_t n) {
    size_t l = 0;
    uint8_t *b = unhex(jstr(o, k), &l);
    int ok = b && l == n;
    if (ok) memcpy(buf, b, n);
    free(b);
    return ok ? 0 : -1;
}

/* the JSON field `k` (hex) equals the n bytes `got` */
static int jeq(json_object *o, const char *k, const uint8_t *got, size_t n) {
    size_t l = 0;
    uint8_t *b = unhex(jstr(o, k), &l);
    int ok = b && l == n && memcmp(b, got, n) == 0;
    free(b);
    return ok;
}

