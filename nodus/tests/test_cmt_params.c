/**
 * Nodus — cometbft @709fd12b C port, wave R1-C: `types/params.go` tests
 * (INACTIVE layer).
 *
 * ── WHAT IT PROVES ─────────────────────────────────────────────────────
 * That ConsensusHash and the parameter rules are the reference's. If this
 * file failed, one of these would be false:
 *   · ConsensusHash is the FLAT hash of the marshalled
 *     HashedParams{Block.MaxBytes, Block.MaxGas} — no Merkle tree — and
 *     the default parameters' preimage is the 16-byte
 *     `088080c00a10ffffffffffffffffff01` the port map pins at REV 3.2;
 *   · NOTHING ELSE IS IN THAT HASH. Changing the evidence bounds, the key
 *     types, the app version or the vote-extension height leaves
 *     ConsensusHash byte-identical, which is exactly what lets the
 *     parameter set evolve without a header change — and, read the other
 *     way, is why the public-key TYPE NAME is not consensus-critical;
 *   · ValidateBasic refuses a zero MaxBytes, a MaxBytes below -1 or above
 *     the 100 MB ceiling, a MaxGas below -1, a non-positive evidence age
 *     or duration, an evidence size above the block bound, a negative
 *     evidence size, a negative vote-extension height, an empty key-type
 *     list and an unknown key type;
 *   · ValidateUpdate implements the ten-row table at params.go:209-219 —
 *     vote extensions cannot be disabled once enabled, cannot be moved to
 *     a past height, and cannot be modified once enabled;
 *   · VoteExtensionsEnabled refuses a height below 1 rather than
 *     answering, and reads an enable height of 0 as NEVER, not as "from
 *     height zero";
 *   · Update applies a sub-message WHOLE when it is present and leaves it
 *     alone when it is absent.
 *
 * ── WHAT IT REQUIRES ───────────────────────────────────────────────────
 * A default build. No compile flags, no environment variables, no
 * network, no files, no clock, no RNG. Safe under `ctest -j`. A few
 * hundred bytes on the stack.
 *
 * ── WHAT IT LEAVES BEHIND ──────────────────────────────────────────────
 * Nothing.
 *
 * ── HOW IT CAN LIE ─────────────────────────────────────────────────────
 *  1. The two SHA3-512 digests are SELF-CONSISTENT FREEZES derived by
 *     shared/dnac/tests/cmt_vset_oracle.py, not cometbft vectors — that
 *     project hashes with SHA-256. The PREIMAGE, however, is checked
 *     against the port map's REV 3.2 golden value, which was derived from
 *     the pinned `params.pb.go`, so the encoding half is grounded even
 *     though the digest half is ours.
 *  2. The key-type name CMT_PUBKEY_TYPE_MLDSA87_NAME is an OPEN QUESTION
 *     for the operator (cmt_params.h). Nothing here asserts its value —
 *     only that the check compares strings and refuses an unknown one. A
 *     green run says nothing about whether that string is the right one.
 *  3. ToProto and ConsensusParamsFromProto are NOT ported (R2 store work),
 *     so nothing here says anything about the parameter wire format —
 *     including the reference's missing nil guard at params.go:349-365,
 *     which is recorded in the header and left for whoever ports it.
 *
 * @file test_cmt_params.c
 */

#include "dnac/cmt_params.h"
