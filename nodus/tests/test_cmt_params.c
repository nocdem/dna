/* ══ 1. the defaults ══════════════════════════════════════════════════ */

static int t_defaults(void)
{
    cmt_consensus_params_t p;

    cmt_default_consensus_params(&p);
    CHECK(p.block.max_bytes == 22020096, "DefaultBlockParams MaxBytes (21MB)");
    CHECK(p.block.max_gas == -1, "DefaultBlockParams MaxGas is -1");
    CHECK(p.evidence.max_age_num_blocks == 100000, "MaxAgeNumBlocks");
    /* 48 hours in NANOSECONDS — a time.Duration is not seconds. */
    CHECK(p.evidence.max_age_duration_ns == (int64_t)48 * 3600 * 1000000000,
          "MaxAgeDuration is 48 hours expressed in nanoseconds");
    CHECK(p.evidence.max_bytes == 1048576, "evidence MaxBytes (1MB)");
    CHECK(p.version.app == 0, "DefaultVersionParams App");
    /* 0 MEANS NEVER, not "from height zero" — params.go:129-130. */
    CHECK(p.abci.vote_extensions_enable_height == 0,
          "DefaultABCIParams: vote extensions are not required");
    CHECK(p.validator.pub_key_types_len == 1, "one key type");
    CHECK(strcmp(p.validator.pub_key_types[0],
                 CMT_PUBKEY_TYPE_MLDSA87_NAME) == 0,
          "the one key type is this chain's");
    CHECK(cmt_consensus_params_validate_basic(&p) == CMT_OK,
          "the defaults are valid");

    /* The three size constants come from cmt_bits.h, not from a copy. */
    CHECK(CMT_MAX_BLOCK_SIZE_BYTES == 104857600, "MaxBlockSizeBytes");
    CHECK(CMT_BLOCK_PART_SIZE_BYTES == 65536, "BlockPartSizeBytes");
    CHECK(CMT_MAX_BLOCK_PARTS_COUNT == 104857600 / 65536 + 1,
          "MaxBlockPartsCount");
    return 0;
}

/* ══ 2. ConsensusHash ═════════════════════════════════════════════════ */

static int t_hash(void)
{
    cmt_consensus_params_t p, q;
    uint8_t                a[64], b[64];

    cmt_default_consensus_params(&p);
    CHECK(cmt_consensus_params_hash(&p, a) == CMT_OK, "Hash");
    CHECK(memcmp(a, V_CONSENSUS_HASH_DEFAULT, 64) == 0,
          "ConsensusHash of the default parameters");

    /* A second point, so a constant-returning implementation fails. */
    memset(&q, 0, sizeof(q));
    q.block.max_bytes = 1;
    q.block.max_gas   = 0;
    CHECK(cmt_consensus_params_hash(&q, b) == CMT_OK, "Hash");
    CHECK(memcmp(b, V_CONSENSUS_HASH_1_0, 64) == 0,
          "ConsensusHash of {1, 0}");
    CHECK(memcmp(a, b, 64) != 0, "and the two differ");

    /* ⚠ ONLY THE TWO BLOCK FIELDS ARE IN THE HASH. Everything else may
     * change without moving the header leaf — params.go:268-271. */
    q = p;
    q.evidence.max_age_num_blocks = 7;
    q.evidence.max_bytes          = 99;
    q.evidence.max_age_duration_ns = 1;
    q.version.app                 = 42;
    q.abci.vote_extensions_enable_height = 5;
    q.validator.pub_key_types_len = 0;
    CHECK(cmt_consensus_params_hash(&q, b) == CMT_OK, "Hash");
    CHECK(memcmp(a, b, 64) == 0,
          "evidence, version, ABCI and key types are NOT in ConsensusHash");

    /* But the two that ARE in it move it. */
    q = p;
    q.block.max_gas = 0;
    CHECK(cmt_consensus_params_hash(&q, b) == CMT_OK, "Hash");
    CHECK(memcmp(a, b, 64) != 0, "Block.MaxGas IS in ConsensusHash");
    q = p;
    q.block.max_bytes = 22020097;
    CHECK(cmt_consensus_params_hash(&q, b) == CMT_OK, "Hash");
    CHECK(memcmp(a, b, 64) != 0, "Block.MaxBytes IS in ConsensusHash");

    CHECK(cmt_consensus_params_hash(NULL, a) == CMT_FAULT, "NULL is a fault");
    return 0;
}

/* ══ 3. ValidateBasic ═════════════════════════════════════════════════ */

static int t_validate_basic(void)
{
    cmt_consensus_params_t p;

#define BAD(field_setup, msg) do {                                   \
        cmt_default_consensus_params(&p);                            \
        field_setup;                                                 \
        CHECK(cmt_consensus_params_validate_basic(&p) == CMT_REJECT, msg); \
    } while (0)
#define GOOD(field_setup, msg) do {                                  \
        cmt_default_consensus_params(&p);                            \
        field_setup;                                                 \
        CHECK(cmt_consensus_params_validate_basic(&p) == CMT_OK, msg); \
    } while (0)

    BAD(p.block.max_bytes = 0,  "a zero Block.MaxBytes is refused");
    BAD(p.block.max_bytes = -2, "a Block.MaxBytes below -1 is refused");
    GOOD(p.block.max_bytes = -1,
         "-1 means unbounded and IS allowed");
    BAD(p.block.max_bytes = (int64_t)CMT_MAX_BLOCK_SIZE_BYTES + 1,
        "a Block.MaxBytes above the 100 MB ceiling is refused");
    GOOD(p.block.max_bytes = CMT_MAX_BLOCK_SIZE_BYTES,
         "exactly the ceiling is allowed");

    BAD(p.block.max_gas = -2, "a Block.MaxGas below -1 is refused");
    GOOD(p.block.max_gas = -1, "-1 is allowed");
    GOOD(p.block.max_gas = 0,  "0 is allowed");

    BAD(p.evidence.max_age_num_blocks = 0,
        "a zero evidence MaxAgeNumBlocks is refused");
    BAD(p.evidence.max_age_num_blocks = -1,
        "a negative evidence MaxAgeNumBlocks is refused");
    BAD(p.evidence.max_age_duration_ns = 0,
        "a zero evidence MaxAgeDuration is refused");

    BAD(p.evidence.max_bytes = p.block.max_bytes + 1,
        "evidence larger than a block is refused");
    GOOD(p.evidence.max_bytes = p.block.max_bytes,
         "evidence exactly the size of a block is allowed");
    BAD(p.evidence.max_bytes = -1, "a negative evidence MaxBytes is refused");
    /* With MaxBytes -1 the evidence bound is the hard ceiling, not -1. */
    GOOD((p.block.max_bytes = -1, p.evidence.max_bytes =
              (int64_t)CMT_MAX_BLOCK_SIZE_BYTES),
         "an unbounded block measures evidence against the ceiling");
    BAD((p.block.max_bytes = -1, p.evidence.max_bytes =
              (int64_t)CMT_MAX_BLOCK_SIZE_BYTES + 1),
        "and one byte past the ceiling is still refused");

    BAD(p.abci.vote_extensions_enable_height = -1,
        "a negative VoteExtensionsEnableHeight is refused");

    BAD(p.validator.pub_key_types_len = 0, "an empty key-type list is refused");
    BAD(memcpy(p.validator.pub_key_types[0], "nosuchtype", 11),
        "an unknown key type is refused");
    BAD(p.validator.pub_key_types_len = CMT_PARAMS_MAX_PUBKEY_TYPES + 1,
        "more key types than capacity is refused");

    CHECK(cmt_consensus_params_validate_basic(NULL) == CMT_FAULT,
          "NULL is a fault");

    /* IsValidPubkeyType compares STRINGS. Its VALUE is an open question
     * for the operator, so nothing here asserts what the string is. */
    cmt_default_consensus_params(&p);
    CHECK(cmt_is_valid_pubkey_type(&p.validator,
                                   CMT_PUBKEY_TYPE_MLDSA87_NAME),
          "the configured type is valid");
    CHECK(!cmt_is_valid_pubkey_type(&p.validator, "ed25519"),
          "a type that is not configured is not valid");
    CHECK(!cmt_is_valid_pubkey_type(&p.validator, ""),
          "the empty string is not valid");
    CHECK(!cmt_is_valid_pubkey_type(NULL, CMT_PUBKEY_TYPE_MLDSA87_NAME),
          "NULL params");
#undef BAD
#undef GOOD
    return 0;
}

/* ══ 4. VoteExtensionsEnabled ═════════════════════════════════════════ */

static int t_vote_extensions(void)
{
    cmt_abci_params_t a;
    bool              on = true;

    a.vote_extensions_enable_height = 0;
    CHECK(cmt_abci_params_vote_extensions_enabled(a, 1, &on) == CMT_OK, "h=1");
    CHECK(!on, "an enable height of 0 means NEVER");
    CHECK(cmt_abci_params_vote_extensions_enabled(a, 1000000, &on) == CMT_OK,
          "h large");
    CHECK(!on, "and it still means never at a large height");

    a.vote_extensions_enable_height = 10;
    CHECK(cmt_abci_params_vote_extensions_enabled(a, 9, &on) == CMT_OK, "h=9");
    CHECK(!on, "off below the enable height");
    CHECK(cmt_abci_params_vote_extensions_enabled(a, 10, &on) == CMT_OK, "h=10");
    CHECK(on, "on AT the enable height");
    CHECK(cmt_abci_params_vote_extensions_enabled(a, 11, &on) == CMT_OK, "h=11");
    CHECK(on, "and above it");

    /* h < 1 is the reference's panic — a verdict, not an answer. */
    CHECK(cmt_abci_params_vote_extensions_enabled(a, 0, &on) == CMT_REJECT,
          "height 0 is refused, not answered");
    CHECK(cmt_abci_params_vote_extensions_enabled(a, -1, &on) == CMT_REJECT,
          "a negative height is refused");
    CHECK(cmt_abci_params_vote_extensions_enabled(a, 1, NULL) == CMT_FAULT,
          "NULL out is a fault");
    return 0;
}

/* ══ 5. ValidateUpdate — the ten-row table ════════════════════════════ */

static int t_validate_update(void)
{
    cmt_consensus_params_t       p;
    cmt_consensus_params_proto_t u;

    cmt_default_consensus_params(&p);
    memset(&u, 0, sizeof(u));

    /* 1: a nil update, or one with no ABCI section, always passes. */
    CHECK(cmt_consensus_params_validate_update(&p, NULL, 100) == CMT_OK,
          "row 1: a nil update passes");
    u.has_abci = false;
    CHECK(cmt_consensus_params_validate_update(&p, &u, 100) == CMT_OK,
          "row 1: an update with no ABCI section passes");

    u.has_abci = true;

    /* 2: a negative height never passes. */
    u.abci.vote_extensions_enable_height = -1;
    CHECK(cmt_consensus_params_validate_update(&p, &u, 100) == CMT_REJECT,
          "row 2: a negative enable height is refused");

    /* 3: currently off, staying off. */
    p.abci.vote_extensions_enable_height = 0;
    u.abci.vote_extensions_enable_height = 0;
    CHECK(cmt_consensus_params_validate_update(&p, &u, 100) == CMT_OK,
          "row 3: off staying off passes");

    /* 4: unchanged. */
    p.abci.vote_extensions_enable_height = 50;
    u.abci.vote_extensions_enable_height = 50;
    CHECK(cmt_consensus_params_validate_update(&p, &u, 100) == CMT_OK,
          "row 4: an unchanged height passes");

    /* 5: ⚠ cannot be DISABLED once it has taken effect. */
    p.abci.vote_extensions_enable_height = 50;
    u.abci.vote_extensions_enable_height = 0;
    CHECK(cmt_consensus_params_validate_update(&p, &u, 100) == CMT_REJECT,
          "row 5: vote extensions cannot be disabled once enabled");
    CHECK(cmt_consensus_params_validate_update(&p, &u, 50) == CMT_REJECT,
          "row 5: not even in the very block they took effect");

    /* 6: a proposal that has NOT taken effect yet may be withdrawn. */
    CHECK(cmt_consensus_params_validate_update(&p, &u, 49) == CMT_OK,
          "row 6: a future enable height may be cancelled");

    /* 7: never to a past or current height. */
    p.abci.vote_extensions_enable_height = 0;
    u.abci.vote_extensions_enable_height = 100;
    CHECK(cmt_consensus_params_validate_update(&p, &u, 100) == CMT_REJECT,
          "row 7: the CURRENT height is refused");
    CHECK(cmt_consensus_params_validate_update(&p, &u, 101) == CMT_REJECT,
          "row 7: a PAST height is refused");

    /* 8: currently off, scheduled for the future. */
    CHECK(cmt_consensus_params_validate_update(&p, &u, 99) == CMT_OK,
          "row 8: an off chain may schedule a future height");

    /* 9: ⚠ cannot be MODIFIED once it has taken effect. */
    p.abci.vote_extensions_enable_height = 50;
    u.abci.vote_extensions_enable_height = 200;
    CHECK(cmt_consensus_params_validate_update(&p, &u, 100) == CMT_REJECT,
          "row 9: vote extensions cannot be modified once enabled");

    /* 10: a future proposal may be moved to another future height. */
    p.abci.vote_extensions_enable_height = 150;
    CHECK(cmt_consensus_params_validate_update(&p, &u, 100) == CMT_OK,
          "row 10: one future height may be replaced by another");

    CHECK(cmt_consensus_params_validate_update(NULL, &u, 1) == CMT_FAULT,
          "NULL params is a fault");
    return 0;
}

/* ══ 6. Update ════════════════════════════════════════════════════════ */

static int t_update(void)
{
    cmt_consensus_params_t       p, out;
    cmt_consensus_params_proto_t u;

    cmt_default_consensus_params(&p);
    memset(&u, 0, sizeof(u));

    /* A nil update is a plain copy and does NOT modify the original.
     * Compared FIELD BY FIELD: a struct assignment is not required to
     * copy padding bytes, so a memcmp over the whole struct would be
     * comparing values C does not define. */
    CHECK(cmt_consensus_params_update(&p, NULL, &out) == CMT_OK, "nil update");
    CHECK(out.block.max_bytes == p.block.max_bytes &&
          out.block.max_gas == p.block.max_gas &&
          out.evidence.max_age_num_blocks == p.evidence.max_age_num_blocks &&
          out.evidence.max_age_duration_ns == p.evidence.max_age_duration_ns &&
          out.evidence.max_bytes == p.evidence.max_bytes &&
          out.version.app == p.version.app &&
          out.abci.vote_extensions_enable_height ==
              p.abci.vote_extensions_enable_height &&
          out.validator.pub_key_types_len == p.validator.pub_key_types_len &&
          strcmp(out.validator.pub_key_types[0],
                 p.validator.pub_key_types[0]) == 0,
          "a nil update copies every field");

    /* An ABSENT sub-message leaves its fields alone. */
    CHECK(cmt_consensus_params_update(&p, &u, &out) == CMT_OK, "empty update");
    CHECK(out.block.max_bytes == p.block.max_bytes &&
          out.version.app == p.version.app,
          "absent sub-messages leave their fields alone");

    /* A PRESENT sub-message is applied WHOLE, zeros included — the code,
     * not the comment at params.go:292, is the authority. */
    u.has_block         = true;
    u.block.max_bytes   = 1024;
    u.block.max_gas     = 0;
    CHECK(cmt_consensus_params_update(&p, &u, &out) == CMT_OK, "block update");
    CHECK(out.block.max_bytes == 1024, "the new MaxBytes");
    CHECK(out.block.max_gas == 0,
          "and a ZERO MaxGas is applied, not skipped as 'non-zero' implies");
    CHECK(p.block.max_gas == -1, "the original is not modified");

    u.has_version = true;
    u.version.app = 9;
    u.has_abci    = true;
    u.abci.vote_extensions_enable_height = 77;
    CHECK(cmt_consensus_params_update(&p, &u, &out) == CMT_OK, "update");
    CHECK(out.version.app == 9 &&
          out.abci.vote_extensions_enable_height == 77, "both applied");
    CHECK(out.evidence.max_bytes == p.evidence.max_bytes,
          "and evidence, which was absent, is untouched");

    /* A key-type list longer than the capacity is refused. */
    u.has_validator = true;
    u.validator.pub_key_types_len = CMT_PARAMS_MAX_PUBKEY_TYPES + 1;
    CHECK(cmt_consensus_params_update(&p, &u, &out) == CMT_REJECT,
          "an over-long key-type list is refused");

    CHECK(cmt_consensus_params_update(NULL, &u, &out) == CMT_FAULT, "NULL");
    CHECK(cmt_consensus_params_update(&p, &u, NULL) == CMT_FAULT, "NULL out");
    return 0;
}

int main(void)
{
    int rc = 0;

    if (rc == 0) { rc = t_defaults();        }
    if (rc == 0) { rc = t_hash();            }
    if (rc == 0) { rc = t_validate_basic();  }
    if (rc == 0) { rc = t_vote_extensions(); }
    if (rc == 0) { rc = t_validate_update(); }
    if (rc == 0) { rc = t_update();          }

    if (rc == 0) {
        printf("test_cmt_params: 6 groups OK\n");
    }
    return rc;
}
