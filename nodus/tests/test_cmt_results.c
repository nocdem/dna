/**
 * Nodus — cometbft @709fd12b C port, wave R1-C: `types/results.go` tests
 * (INACTIVE layer).
 *
 * ── WHAT IT PROVES ─────────────────────────────────────────────────────
 * That LastResultsHash is the reference's. If this file failed, one of
 * these would be false:
 *   · the root is the RFC 6962 Merkle root over the MARSHALLED
 *     ExecTxResults in transaction order, and an EMPTY list gives H("")
 *     — which is what the first block's LastResultsHash is;
 *   · a wholly zero result marshals to ZERO BYTES and its leaf is H(0x00).
 *     That is not a corner case to be defended against: it is the
 *     encoding of a successful transaction that used no gas and returned
 *     no data, and every field of proto3 is omit-zero;
 *   · only Code, Data, GasWanted and GasUsed reach the bytes. The four
 *     fields the reference strips (Log, Info, Events, Codespace) are
 *     application text two honest nodes may write differently, and this
 *     root is inside a header;
 *   · the inclusion proof of a result VERIFIES against the root, and stops
 *     verifying if the leaf or any aunt is tampered with;
 *   · ProveResult refuses an out-of-range index instead of indexing past
 *     the end as the reference's Go would.
 *
 * ── WHAT IT REQUIRES ───────────────────────────────────────────────────
 * A default build. No compile flags, no environment variables, no
 * network, no files, no clock, no RNG. Safe under `ctest -j`. A few
 * kilobytes, all on the stack.
 *
 * ── WHAT IT LEAVES BEHIND ──────────────────────────────────────────────
 * Nothing.
 *
 * ── HOW IT CAN LIE ─────────────────────────────────────────────────────
 *  1. The SHA3-512 roots are SELF-CONSISTENT FREEZES derived by
 *     shared/dnac/tests/cmt_vset_oracle.py, not vectors published by
 *     cometbft (which hashes with SHA-256). They pin that our C and an
 *     independent python agree and that the shape has not drifted; they
 *     do NOT establish that the shape is the reference's.
 *  2. `data` is short here. Nothing exercises a large payload or the
 *     scratch bound at scale.
 *  3. Nothing here checks that the stripped fields are ABSENT from a
 *     decoded message — that is cmt_pb's test (wave R1-A), which pins the
 *     decoder REFUSING them.
 *
 * @file test_cmt_results.c
 */

