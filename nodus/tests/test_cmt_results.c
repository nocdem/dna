/* The three results the vectors above are over. Their marshals, from the
 * oracle:
 *   [0] 08011202aabb2888a40130a09c01      (14 bytes)
 *   [1] (empty)                           ( 0 bytes)
 *   [2] 080712010128ffffffffffffffffff013005  (18 bytes) */
static const uint8_t DATA_0[2] = { 0xaa, 0xbb };
static const uint8_t DATA_2[1] = { 0x01 };

#define SCRATCH_LEN 512
#define MAXN        8

static void fill3(cmt_pb_exec_tx_result_t *r)
{
    cmt_pb_exec_tx_result_init(&r[0]);
    r[0].code       = 1;
    r[0].data.data  = DATA_0;
    r[0].data.len   = sizeof(DATA_0);
    r[0].gas_wanted = 21000;
    r[0].gas_used   = 20000;

    cmt_pb_exec_tx_result_init(&r[1]);   /* wholly zero */

    cmt_pb_exec_tx_result_init(&r[2]);
    r[2].code       = 7;
    r[2].data.data  = DATA_2;
    r[2].data.len   = sizeof(DATA_2);
    r[2].gas_wanted = -1;                /* the 10-byte two's-complement */
    r[2].gas_used   = 5;
}

/* ══ 1. the roots ═════════════════════════════════════════════════════ */

static int t_hash(void)
{
    cmt_pb_exec_tx_result_t r[MAXN];
    cmt_abci_results_t      a;
    cmt_merkle_item_t       items[MAXN];
    uint8_t                 scratch[SCRATCH_LEN];
    uint8_t                 got[64];

    memset(&a, 0, sizeof(a));
    a.results     = r;
    a.results_cap = MAXN;

    /* An EMPTY list is the first block's LastResultsHash: H(""). */
    a.results_len = 0;
    CHECK(cmt_abci_results_hash(&a, scratch, sizeof(scratch), items, MAXN, got)
              == CMT_OK, "Hash of an empty list");
    CHECK(memcmp(got, V_RESULTS_HASH_0, 64) == 0,
          "an empty result list hashes to H(\"\")");

    /* ONE wholly zero result: 0 bytes -> the nil leaf -> H(0x00). */
    fill3(r);
    cmt_pb_exec_tx_result_init(&r[0]);
    a.results_len = 1;
    CHECK(cmt_abci_results_hash(&a, scratch, sizeof(scratch), items, MAXN, got)
              == CMT_OK, "Hash of one zero result");
    CHECK(memcmp(got, V_RESULTS_HASH_1_ZERO, 64) == 0,
          "a zero result marshals to 0 bytes and its leaf is H(0x00)");
    CHECK(memcmp(got, V_RESULTS_HASH_0, 64) != 0,
          "and H(0x00) is NOT H(\"\") — an empty list and a list holding "
          "one empty result are different things");

    /* Three, the middle one zero. */
    fill3(r);
    a.results_len = 3;
    CHECK(cmt_abci_results_hash(&a, scratch, sizeof(scratch), items, MAXN, got)
              == CMT_OK, "Hash of three");
    CHECK(memcmp(got, V_RESULTS_HASH_3, 64) == 0, "the three-result root");

    /* The marshalled lengths the oracle printed. */
    CHECK(cmt_abci_results_to_byte_slices(&a, scratch, sizeof(scratch), items,
                                          MAXN) == CMT_OK, "toByteSlices");
    CHECK(items[0].len == 14, "result 0 marshals to 14 bytes");
    CHECK(items[1].len == 0,  "a wholly zero result marshals to 0 bytes");
    CHECK(items[2].len == 18, "result 2 marshals to 18 bytes (gas -1 is 10)");

    /* ⚠ ORDER IS PART OF THE ROOT — the results are in transaction order
     * and this module never sorts, exactly as the reference never does. */
    {
        cmt_pb_exec_tx_result_t tmp = r[0];
        uint8_t                 other[64];
        r[0] = r[2];
        r[2] = tmp;
        CHECK(cmt_abci_results_hash(&a, scratch, sizeof(scratch), items, MAXN,
                                    other) == CMT_OK, "Hash of a permutation");
        CHECK(memcmp(other, got, 64) != 0, "result order is part of the root");
    }

    /* A scratch buffer that cannot hold the leaves is REFUSED. */
    fill3(r);
    CHECK(cmt_abci_results_hash(&a, scratch, 8, items, MAXN, got) == CMT_REJECT,
          "a short scratch buffer is refused");
    CHECK(cmt_abci_results_hash(&a, scratch, sizeof(scratch), items, 2, got)
              == CMT_REJECT, "too few item slots are refused");
    return 0;
}

/* ══ 2. NewResults and the deterministic copy ═════════════════════════ */

static int t_new_results(void)
{
    cmt_pb_exec_tx_result_t src[MAXN], dst[MAXN], one;
    cmt_abci_results_t      a;

    fill3(src);
    memset(&a, 0, sizeof(a));
    a.results     = dst;
    a.results_cap = MAXN;
    CHECK(cmt_new_results(src, 3, &a) == CMT_OK, "NewResults");
    CHECK(a.results_len == 3, "three results");
    CHECK(dst[0].code == 1 && dst[0].gas_wanted == 21000 &&
          dst[0].gas_used == 20000 && dst[0].data.len == 2,
          "the four deterministic fields survive");
    CHECK(dst[0].data.data == src[0].data.data,
          "the data slice is shared, as the reference's copy shares it");

    CHECK(cmt_deterministic_exec_tx_result(&src[2], &one) == CMT_OK, "det");
    CHECK(one.code == 7 && one.gas_wanted == -1 && one.gas_used == 5 &&
          one.data.len == 1, "the deterministic copy keeps all four fields");

    a.results_cap = 2;
    CHECK(cmt_new_results(src, 3, &a) == CMT_REJECT,
          "more responses than capacity is refused");
    CHECK(cmt_new_results(src, 3, NULL) == CMT_FAULT, "NULL out is a fault");
    return 0;
}

/* ══ 3. ProveResult ═══════════════════════════════════════════════════ */

static int t_prove(void)
{
    cmt_pb_exec_tx_result_t r[MAXN];
    cmt_abci_results_t      a;
    cmt_merkle_item_t       items[MAXN];
    cmt_proof_t             proofs[MAXN], p;
    uint8_t                 scratch[SCRATCH_LEN];
    uint8_t                 root[64];
    size_t                  i;

    fill3(r);
    memset(&a, 0, sizeof(a));
    a.results     = r;
    a.results_cap = MAXN;
    a.results_len = 3;

    CHECK(cmt_abci_results_hash(&a, scratch, sizeof(scratch), items, MAXN,
                                root) == CMT_OK, "root");

    /* Every index has a proof that verifies against that root. */
    for (i = 0; i < 3; i++) {
        CHECK(cmt_abci_results_prove_result(&a, i, scratch, sizeof(scratch),
                                            items, MAXN, proofs, MAXN, &p)
                  == CMT_OK, "ProveResult");
        CHECK(p.total == 3 && p.index == (int64_t)i, "the proof's position");
        CHECK(cmt_proof_verify(&p, root, items[i].data, items[i].len)
                  == CMT_OK, "the proof verifies against the root");
    }

    /* Index 1's aunts are the oracle's. */
    CHECK(cmt_abci_results_prove_result(&a, 1, scratch, sizeof(scratch), items,
                                        MAXN, proofs, MAXN, &p) == CMT_OK,
          "ProveResult(1)");
    CHECK(p.aunts_len == 2, "two aunts in a three-leaf tree");
    CHECK(memcmp(p.aunts[0], V_RESULTS_PROOF1_AUNT0, 64) == 0, "aunt 0");
    CHECK(memcmp(p.aunts[1], V_RESULTS_PROOF1_AUNT1, 64) == 0, "aunt 1");

    /* ⚠ THE PROPERTY AN ATTACKER ATTACKS: a proof must not verify for a
     * value that is not in the tree, nor with a doctored path. */
    {
        uint8_t bad[4] = { 0xde, 0xad, 0xbe, 0xef };
        CHECK(cmt_proof_verify(&p, root, bad, sizeof(bad)) == CMT_REJECT,
              "a proof does not verify for a leaf that is not in the tree");
        p.aunts[0][0] ^= 0x01;
        CHECK(cmt_proof_verify(&p, root, items[1].data, items[1].len)
                  == CMT_REJECT, "a tampered aunt does not verify");
        p.aunts[0][0] ^= 0x01;
        root[0] ^= 0x01;
        CHECK(cmt_proof_verify(&p, root, items[1].data, items[1].len)
                  == CMT_REJECT, "a proof does not verify against another root");
        root[0] ^= 0x01;
        CHECK(cmt_proof_verify(&p, root, items[1].data, items[1].len)
                  == CMT_OK, "and it verifies again once restored");
    }

    /* An out-of-range index is REFUSED, where Go would index past the end. */
    CHECK(cmt_abci_results_prove_result(&a, 3, scratch, sizeof(scratch), items,
                                        MAXN, proofs, MAXN, &p) == CMT_REJECT,
          "an index at the length is refused");
    a.results_len = 0;
    CHECK(cmt_abci_results_prove_result(&a, 0, scratch, sizeof(scratch), items,
                                        MAXN, proofs, MAXN, &p) == CMT_REJECT,
          "an empty list has no proof for any index");
    return 0;
}

int main(void)
{
    int rc = 0;

    if (rc == 0) { rc = t_hash();        }
    if (rc == 0) { rc = t_new_results(); }
    if (rc == 0) { rc = t_prove();       }

    if (rc == 0) {
        printf("test_cmt_results: 3 groups OK\n");
    }
    return rc;
}
