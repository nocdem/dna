/* ══ 1. address derivation and ValidateBasic ══════════════════════════ */

static int t_address(void)
{
    cmt_pb_public_key_t pk;
    cmt_validator_t     v;
    uint8_t             addr[32];

    make_key(&pk, 0x11);
    CHECK(cmt_pub_key_address(&pk, addr) == CMT_OK, "address of key 0");
    CHECK(memcmp(addr, V_ADDR_0, 32) == 0,
          "address of key 0 is SHA3-512(key)[0..31]");

    make_key(&pk, 0x22);
    CHECK(cmt_pub_key_address(&pk, addr) == CMT_OK, "address of key 1");
    CHECK(memcmp(addr, V_ADDR_1, 32) == 0, "address of key 1");

    /* An ABSENT key has no address — the reference's nil PubKey. */
    memset(&pk, 0, sizeof(pk));
    CHECK(cmt_pub_key_address(&pk, addr) == CMT_REJECT,
          "an absent key has no address");
    CHECK(cmt_pub_key_address(NULL, addr) == CMT_FAULT, "NULL key is a fault");

    /* NewValidator derives the address; ValidateBasic re-derives it. */
    make_key(&pk, 0x11);
    CHECK(cmt_validator_new(&pk, 7, &v) == CMT_OK, "NewValidator");
    CHECK(v.address_len == 32 && memcmp(v.address, V_ADDR_0, 32) == 0,
          "NewValidator sets Address = pubKey.Address()");
    CHECK(v.voting_power == 7 && v.proposer_priority == 0,
          "NewValidator sets power and a zero priority");
    CHECK(cmt_validator_validate_basic(&v) == CMT_OK, "a derived validator");

    /* ⚠ THE ATTACK THIS CHECK EXISTS FOR: an address that does not belong
     * to the key must be refused, or a validator could claim another's
     * identity while signing with its own key. */
    v.address[0] ^= 0x01;
    CHECK(cmt_validator_validate_basic(&v) == CMT_REJECT,
          "an address not derived from the key is refused");
    v.address[0] ^= 0x01;

    /* bytes.Equal compares LENGTH too: a truncated address is not equal. */
    v.address_len = 31;
    CHECK(cmt_validator_validate_basic(&v) == CMT_REJECT,
          "a 31-byte address is refused");
    v.address_len = 32;

    v.voting_power = -1;
    CHECK(cmt_validator_validate_basic(&v) == CMT_REJECT,
          "a negative voting power is refused");
    v.voting_power = 7;

    v.pub_key.present = false;
    CHECK(cmt_validator_validate_basic(&v) == CMT_REJECT,
          "a validator with no key is refused");
    CHECK(cmt_validator_validate_basic(NULL) == CMT_REJECT,
          "a NULL validator is the reference's nil validator");
    return 0;
}

/* ══ 2. CompareProposerPriority ═══════════════════════════════════════ */

static int t_compare(void)
{
    cmt_validator_t        a, b;
    const cmt_validator_t *w = NULL;

    make_bare(&a, "aaa", 1);
    make_bare(&b, "bbb", 1);

    /* A nil receiver returns the other — what makes the fold work. */
    CHECK(cmt_validator_compare_proposer_priority(NULL, &b, &w) == CMT_OK &&
          w == &b, "a nil receiver returns the other");

    a.proposer_priority = 5;
    b.proposer_priority = 3;
    CHECK(cmt_validator_compare_proposer_priority(&a, &b, &w) == CMT_OK &&
          w == &a, "the higher priority wins");
    CHECK(cmt_validator_compare_proposer_priority(&b, &a, &w) == CMT_OK &&
          w == &a, "and it wins from either side");

    /* Equal priority: the LOWER address wins. */
    b.proposer_priority = 5;
    CHECK(cmt_validator_compare_proposer_priority(&a, &b, &w) == CMT_OK &&
          w == &a, "on a tie the lower address wins");
    CHECK(cmt_validator_compare_proposer_priority(&b, &a, &w) == CMT_OK &&
          w == &a, "and the tie-break is symmetric");

    /* bytes.Compare orders by length after the common prefix. */
    make_bare(&b, "aaaa", 1);
    b.proposer_priority = 5;
    CHECK(cmt_validator_compare_proposer_priority(&a, &b, &w) == CMT_OK &&
          w == &a, "a prefix sorts before the longer address");

    /* Two identical validators: the reference panics. */
    make_bare(&b, "aaa", 1);
    b.proposer_priority = 5;
    CHECK(cmt_validator_compare_proposer_priority(&a, &b, &w) == CMT_REJECT,
          "two identical validators cannot be compared");
    return 0;
}

/* ══ 3. the clipping arithmetic (J4) ══════════════════════════════════ */

static int t_safemath(void)
{
    int64_t out = 0;

    CHECK(!cmt_vs_safe_add(1, 2, &out) && out == 3, "safeAdd");
    CHECK(cmt_vs_safe_add(INT64_MAX, 1, &out), "safeAdd overflows at the top");
    CHECK(out == -1, "and writes the reference's -1 sentinel");
    CHECK(cmt_vs_safe_add(INT64_MIN, -1, &out),
          "safeAdd overflows at the bottom");
    CHECK(!cmt_vs_safe_sub(1, 2, &out) && out == -1, "safeSub");
    CHECK(cmt_vs_safe_sub(INT64_MIN, 1, &out), "safeSub underflows");
    CHECK(cmt_vs_safe_sub(INT64_MAX, -1, &out), "safeSub overflows");

    /* ⚠ THE J4 PROPERTY: the reference CLIPS, it does not refuse.
     * tm_proposer.c rejects outside ±2^40 instead; this module must not. */
    CHECK(cmt_vs_safe_add_clip(INT64_MAX, 1) == INT64_MAX,
          "safeAddClip clips at the top");
    CHECK(cmt_vs_safe_add_clip(INT64_MIN, -1) == INT64_MIN,
          "safeAddClip clips at the bottom");
    CHECK(cmt_vs_safe_add_clip(INT64_MAX, -1) == INT64_MAX - 1,
          "safeAddClip is ordinary addition in range");
    CHECK(cmt_vs_safe_sub_clip(INT64_MIN, 1) == INT64_MIN,
          "safeSubClip clips at the bottom");
    CHECK(cmt_vs_safe_sub_clip(INT64_MAX, -1) == INT64_MAX,
          "safeSubClip clips at the top");

    CHECK(!cmt_vs_safe_mul(0, INT64_MAX, &out) && out == 0, "safeMul by zero");
    CHECK(!cmt_vs_safe_mul(3, 4, &out) && out == 12, "safeMul");
    CHECK(cmt_vs_safe_mul(INT64_MAX, 2, &out), "safeMul overflows");
    /* The MinInt64 quirk: -b wraps back to MinInt64, so the reference
     * compares against a NEGATIVE divisor and reports overflow. */
    CHECK(cmt_vs_safe_mul(1, INT64_MIN, &out),
          "safeMul reports overflow for b = MinInt64 (reference quirk)");
    return 0;
}

/* ══ 4. the 128-bit average ═══════════════════════════════════════════ */

static int t_avg(void)
{
    cmt_validator_set_t vs;
    int64_t             avg = 0;
    size_t              i;
    struct { int n; int64_t p[3]; int64_t want; } tc[] = {
        { 3, { 0, 0, 0 },                        0            },
        { 3, { INT64_MAX, 0, 0 },                INT64_MAX / 3 },
        { 2, { INT64_MAX, 0, 0 },                INT64_MAX / 2 },
        { 2, { INT64_MAX, INT64_MAX, 0 },        INT64_MAX     },
        { 2, { INT64_MIN, INT64_MIN, 0 },        INT64_MIN     },
    };

    /* validator_set_test.go:474-506, TestAvgProposerPriority. Rows 3 and 4
     * SUM past int64 and are the whole reason for the 128-bit
     * accumulator; an int64 sum would wrap and give the wrong proposer. */
    for (i = 0; i < sizeof(tc) / sizeof(tc[0]); i++) {
        int j;
        CHECK(cmt_validator_set_init(&vs, g_store, CMT_VALSET_MAX) == CMT_OK,
              "init");
        for (j = 0; j < tc[i].n; j++) {
            make_bare(&g_store[j], "x", 0);
            g_store[j].address[0] = (uint8_t)('a' + j);
            g_store[j].proposer_priority = tc[i].p[j];
        }
        vs.validators_len = (size_t)tc[i].n;
        CHECK(cmt_validator_set_compute_avg_proposer_priority(&vs, &avg)
                  == CMT_OK, "computeAvgProposerPriority");
        CHECK(avg == tc[i].want, "the reference's expected average");
    }

    /* Euclidean division floors, so a negative sum rounds DOWN, not toward
     * zero: -1 / 3 is -1, never 0. */
    CHECK(cmt_validator_set_init(&vs, g_store, CMT_VALSET_MAX) == CMT_OK,
          "init");
    for (i = 0; i < 3; i++) {
        make_bare(&g_store[i], "x", 0);
        g_store[i].address[0] = (uint8_t)('a' + i);
        g_store[i].proposer_priority = 0;
    }
    g_store[0].proposer_priority = -1;
    vs.validators_len = 3;
    CHECK(cmt_validator_set_compute_avg_proposer_priority(&vs, &avg) == CMT_OK,
          "avg of {-1, 0, 0}");
    CHECK(avg == -1, "Euclidean division FLOORS: -1/3 is -1, not 0");

    vs.validators_len = 0;
    CHECK(cmt_validator_set_compute_avg_proposer_priority(&vs, &avg)
              == CMT_REJECT, "an empty set has no average");
    return 0;
}

/* ══ 5. ValidatorsHash ════════════════════════════════════════════════ */

static int t_hash(void)
{
    cmt_validator_set_t vs;
    cmt_pb_public_key_t pk;
    uint8_t             got[64];
    const unsigned      seeds[4] = { 0x11, 0x22, 0x33, 0x44 };
    const int64_t       tie_pw[4] = { 5, 5, 5, 9 };
    size_t              i;

    /* An EMPTY set is the empty tree, H(""). */
    CHECK(cmt_validator_set_init(&vs, g_store, CMT_VALSET_MAX) == CMT_OK,
          "init");
    CHECK(hash_set(&vs, got) == CMT_OK, "Hash of an empty set");
    CHECK(memcmp(got, V_VSET_HASH_EMPTY, 64) == 0,
          "Hash() of an empty validator set is H(\"\")");

    /* One validator. */
    make_key(&pk, seeds[0]);
    CHECK(cmt_validator_new(&pk, 10, &g_store[0]) == CMT_OK, "new");
    vs.validators_len = 1;
    CHECK(hash_set(&vs, got) == CMT_OK, "Hash of one validator");
    CHECK(memcmp(got, V_VSET_HASH_1, 64) == 0, "the one-validator root");

    /* Three, IN ValidatorsByVotingPower ORDER: 30, 20, 10. */
    {
        const unsigned s3[3] = { 0x22, 0x33, 0x11 };
        const int64_t  p3[3] = { 30, 20, 10 };
        for (i = 0; i < 3; i++) {
            make_key(&pk, s3[i]);
            CHECK(cmt_validator_new(&pk, p3[i], &g_store[i]) == CMT_OK, "new");
        }
        vs.validators_len = 3;
        CHECK(hash_set(&vs, got) == CMT_OK, "Hash of three");
        CHECK(memcmp(got, V_VSET_HASH_3, 64) == 0, "the three-validator root");

        /* ⚠ ORDER IS PART OF THE ROOT. Swapping two members changes it, so
         * a set assembled in another order does not hash alike — which is
         * why updateWithChangeSet sorts at :674. */
        {
            cmt_validator_t tmp = g_store[0];
            uint8_t         other[64];
            g_store[0] = g_store[1];
            g_store[1] = tmp;
            CHECK(hash_set(&vs, other) == CMT_OK, "Hash of the permutation");
            CHECK(memcmp(other, got, 64) != 0,
                  "leaf order is part of ValidatorsHash");
        }
    }

    /* Four with a POWER TIE, which the ASCENDING address breaks. Build
     * them in DOCUMENT order and let the set's own sort place them. */
    for (i = 0; i < 4; i++) {
        make_key(&pk, seeds[i]);
        CHECK(cmt_validator_new(&pk, tie_pw[i], &g_store[i]) == CMT_OK, "new");
    }
    {
        cmt_validator_t *ptrs[4];
        for (i = 0; i < 4; i++) {
            ptrs[i] = &g_store[i];
        }
        cmt_validators_sort_by_voting_power(ptrs, 4);
        for (i = 0; i < 4; i++) {
            CHECK(ptrs[i] == &g_store[(size_t)V_VSET_4_TIE_ORDER[i]],
                  "power DESC, then address ASC");
        }
        for (i = 0; i < 4; i++) {
            g_store2[i] = *ptrs[i];
        }
    }
    CHECK(cmt_validator_set_init(&vs, g_store2, CMT_VALSET_MAX) == CMT_OK,
          "init");
    vs.validators_len = 4;
    CHECK(hash_set(&vs, got) == CMT_OK, "Hash of four with a tie");
    CHECK(memcmp(got, V_VSET_HASH_4_TIE, 64) == 0,
          "the tie-broken four-validator root");

    /* A leaf is at most CMT_VALIDATOR_BYTES_MAX, and a keyless validator
     * has no leaf at all. */
    {
        uint8_t buf[CMT_VALIDATOR_BYTES_MAX];
        size_t  len = 0;
        CHECK(cmt_validator_bytes(&g_store2[0], buf, sizeof(buf), &len)
                  == CMT_OK, "Bytes()");
        CHECK(len <= CMT_VALIDATOR_BYTES_MAX,
              "a leaf fits CMT_VALIDATOR_BYTES_MAX");
        CHECK(cmt_validator_bytes(&g_store2[0], buf, len - 1, &len)
                  == CMT_REJECT, "an exact-size-minus-one buffer is refused");
        g_store2[0].pub_key.present = false;
        CHECK(cmt_validator_bytes(&g_store2[0], buf, sizeof(buf), &len)
                  == CMT_REJECT, "a keyless validator has no leaf");
    }
    return 0;
}

