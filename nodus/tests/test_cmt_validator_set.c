/**
 * Nodus — cometbft @709fd12b C port, wave R1-C: `types/validator.go` +
 * `types/validator_set.go` tests (INACTIVE layer).
 *
 * ── WHAT IT PROVES ─────────────────────────────────────────────────────
 * That the validator set that produces ValidatorsHash and elects every
 * proposer is the reference's. If this file failed, one of these would be
 * false:
 *   · a validator's address is SHA3-512(pubkey)[0..31] — the derivation
 *     this tree already uses for a witness id — and ValidateBasic
 *     RE-DERIVES it rather than trusting the one it was handed, so an
 *     address cannot be forged onto a key;
 *   · ValidatorsHash is the Merkle root over SimpleValidator{PubKey,
 *     VotingPower} leaves in ValidatorsByVotingPower order (power
 *     descending, address ascending), and an EMPTY set hashes to H("");
 *   · THE PROPOSER SEQUENCE IS COMETBFT'S. The 99-step sequence of
 *     TestProposerSelection1 (validator_set_test.go:221-241) and the
 *     40/50/30 proportionality of TestProposerSelection2 (:296-334) are
 *     the reference's own expected values, and this port reproduces them
 *     step for step;
 *   · the average that centres the priorities is computed at 128 bits —
 *     TestAvgProposerPriority's MaxInt64 and MinInt64 rows
 *     (validator_set_test.go:474-506) are exactly the cases an int64
 *     accumulator gets wrong, and getting them wrong changes who
 *     proposes;
 *   · a change set refuses a duplicate address, a negative power and a
 *     power above MaxTotalVotingPower; a zero power is a REMOVAL, not an
 *     error; and NewValidatorSet refuses a removal where
 *     UpdateWithChangeSet allows one;
 *   · a total voting power above MaxTotalVotingPower is a FAULT and not a
 *     verdict — a caller must never turn it into "this block is invalid";
 *   · safeAddClip and safeSubClip CLIP to the int64 ends instead of
 *     refusing, which is the J4 deviation of the deviation register that
 *     this module exists not to repeat;
 *   · GetProposer returns the STORED proposer, not a recomputed one. The
 *     two genuinely differ right after an election, because the elected
 *     validator has just been pushed back by the total voting power.
 *
 * ── WHAT IT REQUIRES ───────────────────────────────────────────────────
 * A default build. No compile flags, no environment variables, no
 * network, no files, no clock, no RNG. Safe under `ctest -j`. It allocates
 * a little over 2 MB on the heap (the change-set scratch and a 128-slot
 * validator array, each validator carrying a 2592-byte key) and frees it.
 *
 * ── WHAT IT LEAVES BEHIND ──────────────────────────────────────────────
 * Nothing. No files, no directories, no processes, no global state.
 *
 * ── HOW IT CAN LIE ─────────────────────────────────────────────────────
 *  1. The SHA3-512 digests are SELF-CONSISTENT FREEZES, not cometbft
 *     vectors: cometbft hashes with SHA-256 and the substitution is ours.
 *     They were derived by shared/dnac/tests/cmt_vset_oracle.py, an
 *     implementation independent of this C, so they pin agreement between
 *     two implementations and that the shape has not drifted. They do NOT
 *     establish that the shape is the reference's.
 *     THE PROPOSER SEQUENCES ARE DIFFERENT IN KIND — those ARE cometbft's
 *     own expected values, copied from its test file, and the oracle
 *     reproduces them from an independently written algorithm before it
 *     will emit anything.
 *  2. The proposer-selection sets are KEYLESS with short addresses,
 *     exactly as validator_set_test.go:400-402's `newValidator` builds
 *     them. That is what makes the reference's vectors reusable, and it
 *     means those cases exercise the ARITHMETIC and the tie-break, never
 *     the key handling. The hash cases carry real 2592-byte keys.
 *  3. Nothing here builds a 128-validator set or a real ML-DSA-87 key
 *     pair. The capacity bound is tested at its edge, not at scale.
 *  4. VerifyCommit and the light-client methods are NOT ported (stage D),
 *     so nothing here says anything about commit verification.
 *
 * @file test_cmt_validator_set.c
 */

