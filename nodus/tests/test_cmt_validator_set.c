/* ══ fixtures ═════════════════════════════════════════════════════════ */

/** cmt_pb_oracle.py's `pat`: byte i = (seed + 7*i) mod 256. */
static void fill_pat(uint8_t *dst, size_t n, unsigned seed)
{
    size_t i;
    for (i = 0; i < n; i++) {
        dst[i] = (uint8_t)((seed + 7u * (unsigned)i) & 0xFFu);
    }
}

static void make_key(cmt_pb_public_key_t *pk, unsigned seed)
{
    memset(pk, 0, sizeof(*pk));
    pk->present = true;
    fill_pat(pk->key, CMT_PB_PUBKEY_LEN, seed);
}

/** A KEYLESS validator with a short literal address — exactly what
 *  validator_set_test.go:400-402's `newValidator` builds. */
static void make_bare(cmt_validator_t *v, const char *addr, int64_t power)
{
    size_t n = strlen(addr);
    memset(v, 0, sizeof(*v));
    memcpy(v->address, addr, n);
    v->address_len  = n;
    v->voting_power = power;
}

/** A keyless validator with a 20-byte address whose last byte is `tag` —
 *  the addr0/addr1/addr2 of validator_set_test.go:244-246. */
static void make_bare20(cmt_validator_t *v, uint8_t tag, int64_t power)
{
    memset(v, 0, sizeof(*v));
    v->address_len   = 20;
    v->address[19]   = tag;
    v->voting_power  = power;
}

