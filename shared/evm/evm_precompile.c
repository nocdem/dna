/* evm.h: the tag address is SHA3-512(EVM_MLDSA87_TAG)[0..32] */
static int mldsa87_addr_check(void)
{
    uint8_t h[QGP_SHA3_512_DIGEST_LENGTH];
    if (qgp_sha3_512((const uint8_t *)EVM_MLDSA87_TAG, EVM_MLDSA87_TAG_LEN,
                     h) != 0)
        return 0;
    return memcmp(h, evm_mldsa87_addr.b, 32) == 0;
}

/* One PC_KATS32 row through the interpreter's dispatch. @return 1 match. */
static int kat32_run(const pc_kat32_t *k, int *alloc_failed)
{
    size_t in_len = 0, off = 0, out_len = 0;
    uint8_t *in, *out = NULL;
    uint64_t gas = 10000000u, start = gas;
    evm_pc_result_t res = EVM_PC_INVALID;
    evm_config_t cfg;
    int ok;

    for (int p = 0; p < 3; p++) in_len += k->part_len[p];
    in = malloc(in_len ? in_len : 1);
    if (!in) {
        *alloc_failed = 1;
        return 0;
    }
    for (int p = 0; p < 3; p++) {
        if (k->part[p]) memcpy(in + off, k->part[p], k->part_len[p]);
        else memset(in + off, 0, k->part_len[p]);
        off += k->part_len[p];
    }
    /* the node's Nodus configuration with every tag precompile on */
    memset(&cfg, 0, sizeof(cfg));
    cfg.fork = EVM_FORK_PRAGUE;
    cfg.addr_bytes = 32;
    cfg.precompile_mask = EVM_PRECOMPILES_PRAGUE;
    cfg.nodus_profile = 1;
    cfg.mldsa_precompile = 1;
    ok = evm_precompile_run_cfg(&cfg, k->addr, in, in_len, &gas, &res, &out,
                                &out_len) == 0 &&
         res == EVM_PC_OK && start - gas == k->gas &&
         out_len == (k->want ? k->want_len : 0) &&
         (out_len == 0 || memcmp(out, k->want, out_len) == 0);
    free(in);
    free(out);
    return ok;
}

/* hex string -> fresh buffer; NULL on malformed input or allocation */
static uint8_t *kat_hex(const char *hex, size_t *n)
{
    size_t hl = strlen(hex);
    uint8_t *b;
    if (hl % 2 != 0) return NULL;
    *n = hl / 2;
    b = malloc(*n ? *n : 1);
    if (!b) return NULL;
    for (size_t i = 0; i < *n; i++) {
        int hi = hex_nibble((uint8_t)hex[2 * i]);
        int lo = hex_nibble((uint8_t)hex[2 * i + 1]);
        if (hi < 0 || lo < 0) {
            free(b);
            return NULL;
        }
        b[i] = (uint8_t)((hi << 4) | lo);
    }
    return b;
}

