static void check2(const evm_membackend *mb)
{
    check_begin("check2_stack_address_uses_full_word");
    changes_t cs;
    evm_exec_status_t status;
    int rc = run_single_call(mb, ADDR32_TWIN_DRIVER, &cs, &status);
    expect(rc == 0, "tx applied");
    expect(status == EVM_EXEC_SUCCESS, "tx succeeded");
    post_t p = { mb, &cs };
    const uint8_t *D = ADDR32_TWIN_DRIVER;
    evm_addr xhi = mkaddr(ADDR32_X_HI), xlo = mkaddr(ADDR32_X_LO);
    const evm_mem_account *mhi = evm_membackend_find(mb, &xhi);
    const evm_mem_account *mlo = evm_membackend_find(mb, &xlo);
    if (!mhi || !mlo) fatal("twin pre-state missing");

    /* BALANCE */
    expect_slot_u64(&p, D, 0x10, BAL_X_HI, "BALANCE(X_HI)");
    expect_slot_u64(&p, D, 0x11, BAL_X_LO, "BALANCE(X_LO)");
    expect_slot_u64(&p, D, 0x12, 0, "BALANCE(20-byte projection) = 0");
    /* EXTCODESIZE */
    expect_slot_u64(&p, D, 0x20, mhi->code_len, "EXTCODESIZE(X_HI)");
    expect_slot_u64(&p, D, 0x21, mlo->code_len, "EXTCODESIZE(X_LO)");
    expect_slot_u64(&p, D, 0x22, 0, "EXTCODESIZE(projection) = 0");
    expect(mhi->code_len != mlo->code_len, "fixture: twin code sizes differ");
    /* EXTCODEHASH */
    expect_slot(&p, D, 0x30, mhi->code_hash.b, "EXTCODEHASH(X_HI)");
    expect_slot(&p, D, 0x31, mlo->code_hash.b, "EXTCODEHASH(X_LO)");
    expect_slot(&p, D, 0x32, ZERO32, "EXTCODEHASH(absent projection) = 0");
    /* EXTCODECOPY: first 32 bytes, zero padded */
    {
        uint8_t w[32] = {0};
        memcpy(w, mhi->code, mhi->code_len);
        expect_slot(&p, D, 0x40, w, "EXTCODECOPY(X_HI)");
        memset(w, 0, 32);
        memcpy(w, mlo->code, mlo->code_len);
        expect_slot(&p, D, 0x41, w, "EXTCODECOPY(X_LO)");
    }
    /* CALL with value */
    expect_slot_u64(&p, D, 0x50, 1, "CALL X_HI succeeded");
    expect_slot_u64(&p, D, 0x51, 1, "CALL X_LO succeeded");
    expect_slot_u64(&p, ADDR32_X_HI, 0, 0xA1, "X_HI code wrote X_HI storage");
    expect_slot_u64(&p, ADDR32_X_LO, 0, 0xB2, "X_LO code wrote X_LO storage");
    expect_balance_u64(&p, ADDR32_X_HI, BAL_X_HI + 1, "X_HI balance += 1");
    expect_balance_u64(&p, ADDR32_X_LO, BAL_X_LO + 2, "X_LO balance += 2");
    expect(!post_exists(&p, ADDR32_X_PROJ), "20-byte projection not created");
    expect_slot_u64(&p, ADDR32_X_PROJ, 0, 0, "projection storage untouched");
    expect_balance_u64(&p, D, BAL_DRIVER - 3, "driver paid 1 + 2");
    /* STATICCALL */
    expect_slot_u64(&p, D, 0x60, 1, "STATICCALL Y_HI succeeded");
    expect_slot_u64(&p, D, 0x61, 0xA2, "STATICCALL Y_HI ran Y_HI code");
    expect_slot_u64(&p, D, 0x62, 1, "STATICCALL Y_LO succeeded");
    expect_slot_u64(&p, D, 0x63, 0xB3, "STATICCALL Y_LO ran Y_LO code");
    /* DELEGATECALL */
    expect_slot_u64(&p, D, 0x70, 1, "DELEGATECALL Z_HI succeeded");
    expect_slot_u64(&p, D, 0x71, 0xA3, "DELEGATECALL Z_HI ran Z_HI code");
    expect_slot_u64(&p, D, 0x72, 1, "DELEGATECALL Z_LO succeeded");
    expect_slot_u64(&p, D, 0x73, 0xB4, "DELEGATECALL Z_LO ran Z_LO code");
    expect_slot_u64(&p, ADDR32_Z_HI, 0x71, 0, "Z_HI own storage untouched");
    expect_slot_u64(&p, ADDR32_Z_LO, 0x73, 0, "Z_LO own storage untouched");
    /* CALLCODE */
    expect_slot_u64(&p, D, 0x80, 1, "CALLCODE W_HI succeeded");
    expect_slot_u64(&p, D, 0x81, 0xA4, "CALLCODE W_HI ran W_HI code");
    expect_slot_u64(&p, D, 0x82, 1, "CALLCODE W_LO succeeded");
    expect_slot_u64(&p, D, 0x83, 0xB5, "CALLCODE W_LO ran W_LO code");
    expect_slot_u64(&p, ADDR32_W_HI, 0x81, 0, "W_HI own storage untouched");
    expect_slot_u64(&p, ADDR32_W_LO, 0x83, 0, "W_LO own storage untouched");
    /* SELFDESTRUCT (pre-existing contract: EIP-6780 keeps it, moves balance) */
    expect_slot_u64(&p, D, 0x90, 1, "CALL SD succeeded");
    expect_balance_u64(&p, ADDR32_S_HI, BAL_SD, "beneficiary S_HI got SD balance");
    expect_balance_u64(&p, ADDR32_S_LO, BAL_S_LO, "twin S_LO unchanged");
    expect_balance_u64(&p, ADDR32_S_PROJ, 0, "projection S_PROJ got nothing");
    expect(!post_exists(&p, ADDR32_S_PROJ), "projection S_PROJ not created");
    expect_balance_u64(&p, ADDR32_SD, 0, "SD balance moved out");
    expect(post_exists(&p, ADDR32_SD), "SD not deleted (not created this tx)");
    changes_free(&cs);
    check_end();
}

