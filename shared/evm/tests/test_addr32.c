/**
 * @file test_addr32.c
 * @brief Nodus EVM 32-byte address mode (cfg.addr_bytes = 32) — engine checks.
 *
 * Spec under test: docs/plans/2026-10-04-nodus-evm-engine-design.md §2
 * (decision docs/plans/decisions/2026-10-04-nodus-evm-domain.md, item 3;
 * Kurultay nodus-evm-k1 consensus item 2). The official Ethereum state tests only
 * cover addr_bytes = 20; this file pins the 32-byte behaviour with
 * hand-assembled bytecode run through the public API (evm.h) over the
 * test-only in-memory backend (tests/evm_membackend.c).
 *
 * Every account address used below has non-zero HIGH 12 bytes unless it is
 * deliberately a "20-byte projection" (12 zero bytes || the same low 20) or
 * a numeric precompile address. Addresses, init code, salt and the expected
 * CREATE / CREATE2 / create-tx addresses come from tests/addr32_vectors.h,
 * generated by tests/addr32_oracle.py (its own Keccak-f[1600] and RLP; no
 * engine or shared/crypto code).
 *
 * Checks (each prints PASS/FAIL under its name):
 *   check1_env_opcodes_push_full_word
 *       ADDRESS / CALLER / ORIGIN / COINBASE push all 32 bytes (CALLER !=
 *       ORIGIN: the observing contract is reached through an intermediary).
 *   check2_stack_address_uses_full_word
 *       CALL / STATICCALL / DELEGATECALL / CALLCODE / BALANCE / EXTCODESIZE /
 *       EXTCODEHASH / EXTCODECOPY / SELFDESTRUCT beneficiary: twin accounts
 *       with the same low 20 bytes and different high 12 bytes are distinct,
 *       and the 20-byte projection (absent) reads as empty.
 *   check3_create_create2_full_hash
 *       CREATE = keccak256(rlp([sender_32, nonce])) at nonces 0x7f and 0x80;
 *       CREATE2 = keccak256(0xff || sender_32 || salt || keccak256(init));
 *       all 32 bytes, pushed on the stack and used as the account key.
 *   check4_precompile_match_full_word
 *       0x00..01 is ecrecover (returns 32 bytes for a valid signature);
 *       0xff*12 || 0..01 is an ordinary empty account (returns nothing,
 *       receives value). Same for identity 0x04.
 *   check5_create_tx_result_created
 *       top-level create tx: res->created = oracle value (nonces 0, 0x0100).
 *   check6_eip3541_and_7702_designator
 *       0xEF-prefixed code is refused (create tx and nested CREATE); a
 *       pre-state 7702 designator (0xef0100 || 20-byte target) is followed
 *       with the target RIGHT-ALIGNED into 32 bytes (12 zero bytes || 20),
 *       through a CALL and as a top-level tx target; a decoy at
 *       (non-zero high || same 20 bytes) never runs.
 *   check7_change_set_deterministic
 *       the same transaction sequence on two fresh states yields
 *       byte-identical serialized change sets.
 *
 * Standalone harness (like tests/test_u256.c): reports via fprintf;
 * exit 0 = every check passed, 1 = a check failed, 2 = engine fault/OOM.
 */
