/* A Nodus-style 32-byte chain id with non-zero high bytes (evm.h: never
 * truncated). */
static void chain_id(evm_u256 *out)
{
    uint8_t b[32];
    for (int i = 0; i < 32; i++) b[i] = (uint8_t)(0xA0 + i);
    evm_u256_from_be(out, b);
}

static void make_cfg(evm_config_t *cfg)
{
    memset(cfg, 0, sizeof(*cfg));
    cfg->fork = EVM_FORK_PRAGUE;
    cfg->addr_bytes = 32;
    chain_id(&cfg->chain_id);
    /* precompile set is configuration (evm.h precompile_mask, red-team
     * round 1 fix 7): this file pins the Prague set */
    cfg->precompile_mask = EVM_PRECOMPILES_PRAGUE;
}

static void make_env(evm_block_env_t *env)
{
    memset(env, 0, sizeof(*env));
    memcpy(env->coinbase.b, ADDR32_COINBASE, 32);
    env->number = 100;
    env->timestamp = 1000;
    env->gas_limit = 30000000;
    evm_u256_from_u64(&env->base_fee, 7);
}

typedef struct {
    evm_backend_t   be;
    evm_config_t    cfg;
    evm_block_env_t env;
    evm_state_t    *st;
} run_t;

static void run_open(run_t *r, const evm_membackend *mb)
{
    make_cfg(&r->cfg);
    make_env(&r->env);
    evm_membackend_bind(mb, &r->be);
    r->st = evm_state_new(&r->cfg, &r->be);
    if (!r->st) fatal("evm_state_new");
}

static void run_close(run_t *r)
{
    evm_state_free(r->st);
    r->st = NULL;
}

/* legacy (type 0) tx with the configured chain id; returns evm_tx_apply's
 * return value; a fault (-2) is fatal. */
static int run_tx(run_t *r, const uint8_t from[32], uint64_t nonce,
                  const uint8_t *to, const uint8_t *data, size_t data_len,
                  evm_tx_result_t *res)
{
    evm_tx_t tx;
    memset(&tx, 0, sizeof(tx));
    tx.type = 0;
    memcpy(tx.sender.b, from, 32);
    if (to) memcpy(tx.to.b, to, 32);
    else tx.is_create = 1;
    tx.nonce = nonce;
    tx.gas_limit = 5000000;
    evm_u256_from_u64(&tx.gas_price, 10);
    tx.data = data;
    tx.data_len = data_len;
    tx.has_chain_id = 1;
    chain_id(&tx.chain_id);
    int rc = evm_tx_apply(r->st, &r->env, &tx, res);
    if (rc == -2) fatal("evm_tx_apply fault");
    return rc;
}

/* one call tx from SENDER (nonce 3) on a fresh state; change set into cs */
static int run_single_call(const evm_membackend *mb, const uint8_t to[32],
                           changes_t *cs, evm_exec_status_t *status)
{
    run_t r;
    evm_tx_result_t res;
    run_open(&r, mb);
    int rc = run_tx(&r, ADDR32_SENDER, 3, to, NULL, 0, &res);
    *status = res.status;
    if (rc == 0) collect(r.st, cs);
    else memset(cs, 0, sizeof(*cs));
    evm_tx_result_free(&res);
    run_close(&r);
    return rc;
}

