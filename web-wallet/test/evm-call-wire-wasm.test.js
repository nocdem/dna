test('F9: an offline CALL refuses a malformed estimate and takes one at the read bound', { skip }, async () => {
  const READS_BASE = 16334n;                // (30 000 000 + 2 099) / 2 100 + 2 048
  const callWith = ue => offlineEvm({ op: 1, to: TO, value: '00'.repeat(32), gas: '50000', estimate: [ue.toString(), '50000'] });
  // no estimate: the minimum of this envelope's shape — one input, one
  // change, the default declaration, no access list: the REFERENCE shape
  const ref = await offlineEvm({ op: 1, to: TO, value: '00'.repeat(32), gas: '50000' });
  assert.equal(ref.rc, 0, ref.error);
  assert.equal(ref.nIn, 1, 'one funding input: the reference shape');
  const R = ref.units;
  const atRef = await callWith(R);
  assert.equal(atRef.rc, 0, atRef.error);
  assert.equal(atRef.units, R);
  const atBound = await callWith(R + READS_BASE);
  assert.equal(atBound.rc, 0, atBound.error);
  assert.equal(atBound.units, R + READS_BASE);
  const over = await callWith(R + READS_BASE + 1n);
  assert.notEqual(over.rc, 0);
  assert.match(over.error, /more reads than a transaction may make/);
  const below = await callWith(R - 1n);
  assert.notEqual(below.rc, 0);
  assert.match(below.error, /below the smallest one possible/);
});

