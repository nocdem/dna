// Smart contracts — the C call-bytes codec (shared/dnac/evm_call_wire.c) and
// the EVM envelope builder (crypto/nodus-send-wasm.c "SMART CONTRACTS")
// through the module.
//
// Always run (the committed src/nodus/send.wasm): the shipped module exports
// every smart-contract entry point send-module.js calls and none of the
// test-only ones.
//
// With NODUS_SEND_PARITY_OUT (`scripts/build-nodus-send-wasm.sh parity`;
// otherwise these SKIP — a skip is not a pass), on the TEST wasm:
//   - every EVM op's call bytes equal a layout assembled HERE from design
//     docs/plans/2026-10-04-nodus-evm-chain-integration-design.md rev 3 §2 (the
//     same shapes as the node test's own encoder, nodus/tests/test_v2_evm.c
//     enc_call / enc_create / enc_deposit / enc_withdraw / enc_redeem), and
//     decode -> re-encode returns them unchanged;
//   - the decoder refuses what the node's rtevm_decode refuses: a trailing
//     byte, a short call, a wrong version, an access-list key count past the
//     data, a CREATE initcode over 49 152 bytes;
//   - the EVMFUND call (the node's layout since Nodus EVM Faz 4 — the node decodes
//     it with the same codec, evm_call_wire.h) round-trips and its refusals
//     (role, input order, change count 0..16, owner case, zero amount,
//     non-native token);
//   - an offline DEPOSIT build: two legs CORE op 9 (role DEPOSIT) then EVM op
//     3, the deposit call bytes, Σinputs = amount + fee + change, fee =
//     max(floor, units × gas price); built twice from the same fixed
//     randomness it is the same envelope; without a meter weight for CORE op
//     9 (generation 2's pinned policy has none) the build refuses; a
//     declared ceiling below the minimum refuses;
//   - red-team 1 F11: the shared CREATE-address rule
//     (nodus/src/client/nodus_v2_evm.c nodus_v2_evm_create_address) equals
//     the engine's INDEPENDENT oracle vectors (shared/evm/tests/
//     addr32_vectors.h, generated by addr32_oracle.py — read from that file
//     here, nonces 0, 0x7f, 0x80, 0x100), and an offline CREATE build's
//     nsw_evm_built_created is that rule on the signed sender and nonce
//     (also re-derived here with @noble/hashes keccak_256 over the RLP);
//     every other op gives "";
//   - red-team 1 F9: an offline CALL build refuses an estimate whose `ue` is
//     below the reference shape's units or whose read units exceed
//     EVM_READS_BASE (16 334) × w_read (1, nodus_ruleset_pins.h
//     NODUS_PIN_G2_SYS_METER_W_READ), and takes one at exactly the bound;
//   - red-team 1 F4: the §18 query argument text's `U` tag (`c=U:h,x,li`,
//     the evm_logs cursor) encodes to a CBOR array of 1..3 uints (bytes
//     assembled HERE from RFC 8949 major types), and an empty element,
//     more than 3 elements, a leading zero, 2^64 refuse.
// Inputs are SYNTHETIC (fixed seed, made-up coins, chain id and EVM ruleset
// hash, op weight 9 = 1 on top of generation 2): they prove the module's
// codec and envelope shape (the shared builder nodus_v2_evm.c since Nodus EVM
// Faz 4) — NOT that a node accepts the envelope (the node decodes these
// bytes with the same codec, but no node runs here).
