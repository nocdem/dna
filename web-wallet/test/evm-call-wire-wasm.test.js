// shared/dnac/env_wire.h "Canonical wire layout"
function parseEnvelope(b) {
  assert.equal(b.subarray(0, 16).toString('latin1'), 'NDS.ENVWIRE.v1\0\0');
  const n = b.readUInt16BE(41), legs = [];
  let off = 43 + 30 * n;
  for (let i = 0; i < n; i++) {
    const h = 43 + 30 * i;
    legs.push({ domain: b.readUInt32BE(h), op: b.readUInt32BE(h + 4), ver: b.readUInt32BE(h + 8), access: b[h + 12], kind: b[h + 13], callLen: b.readUInt32BE(h + 14), authLen: b.readUInt32BE(h + 18), effects: b.readUInt32BE(h + 22), effectBytes: b.readUInt32BE(h + 26) });
  }
  for (const leg of legs) { leg.call = b.subarray(off, off + leg.callLen).toString('hex'); off += leg.callLen; }
  return { expiry: b.readBigUInt64BE(17), fee: b.readBigUInt64BE(25), units: b.readBigUInt64BE(33), legs };
}

test('offline DEPOSIT build: [CORE op 9, role DEPOSIT] + [EVM op 3], amounts add up, same bytes twice', { skip }, async () => {
  const a = await offlineDeposit();
  assert.equal(a.rc, 0, a.error);
  const e = parseEnvelope(a.env);
  assert.equal(e.legs.length, 2);
  assert.deepEqual(e.legs.map(l => [l.domain, l.op, l.access, l.kind]), [[1, 9, 2, 1], [2, 3, 2, 1]]);
  assert.equal(e.legs[0].ver, a.coreVer);
  assert.equal(e.legs[1].ver, 1);
  assert.equal(e.legs[1].call, '01' + be(BUILD.amount, 8) + be(BUILD.nonce, 8));
  assert.equal(a.op, 3); assert.equal(a.amount, BUILD.amount);
  assert.equal(e.expiry, 1090n); assert.equal(e.fee, a.fee); assert.equal(e.units, a.units);
  assert.ok(a.units > 0n);
  // fee = max(floor, units × gas price); the floor is below this product here
  assert.equal(a.fee, a.units * 121n);
  // the funding call: role DEPOSIT, the inputs ascending, one change to the sender
  const call = Buffer.from(e.legs[0].call, 'hex');
  assert.equal(call[0], 1); assert.equal(call[1], 2);
  const nIn = call[2];
  const nuls = Array.from({ length: nIn }, (_, i) => call.subarray(3 + 64 * i, 3 + 64 * (i + 1)).toString('hex'));
  assert.deepEqual(nuls, [...nuls].sort());
  assert.deepEqual(nuls, a.inputs);
  const amounts = new Map(BUILD.coins);
  const inSum = nuls.reduce((s, n) => s + BigInt(amounts.get(n)), 0n);
  assert.equal(inSum, BigInt(BUILD.amount) + a.fee + a.change);
  // same inputs, same fixed randomness: the same envelope byte for byte
  const b = await offlineDeposit();
  assert.equal(b.env.toString('hex'), a.env.toString('hex'));
  assert.equal(b.intent, a.intent);
});

