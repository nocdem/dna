const be = (v, n) => BigInt(v).toString(16).padStart(2 * n, '0');
function setData({ M, num }, hex) {
  if (!hex) { num('nsw_evm_data_alloc', ['number'], [0]); return; }
  const at = num('nsw_evm_data_alloc', ['number'], [hex.length / 2]);
  assert.ok(at);
  M.HEAPU8.set(Buffer.from(hex, 'hex'), at);
}
// encode through the module: op, to, value, gas, nonce, amount, dest, ticket
const enc = (mod, op, f) => mod.str('nsw_test_evm_call_hex', ['number', 'string', 'string', 'string', 'string', 'string', 'string', 'string'],
  [op, f.to ?? '', f.value ?? '', f.gas ?? '0', f.nonce ?? '0', f.amount ?? '0', f.dest ?? '', f.ticket ?? '']);
const roundtrip = (mod, op, hex) => mod.str('nsw_test_evm_call_roundtrip', ['number', 'string'], [op, hex]);

const TO = 'ab'.repeat(32), VALUE = '00'.repeat(24) + be(10n ** 18n, 8), ACC_ADDR = 'cd'.repeat(32), ACC_KEY = '01'.repeat(32);
const DEST = 'ee'.repeat(64), TICKET = '77'.repeat(64), DATA = 'a9059cbb' + '00'.repeat(64), INIT = '6080604052' + 'fe'.repeat(11);

test('EVM call bytes: each op equals the §2 layout and round-trips', { skip }, async () => {
  const mod = await testModule();
  // CALL with one access-list entry holding one key
  mod.num('nsw_evm_access_reset');
  assert.equal(mod.num('nsw_evm_access_add', ['string', 'string'], [ACC_ADDR, ACC_KEY]), 0, mod.str('nsw_error'));
  setData(mod, DATA);
  const call = enc(mod, 1, { to: TO, value: VALUE, gas: '100000', nonce: '7' });
  const callRef = '01' + TO + VALUE + be(100000, 8) + be(7, 8) + be(1, 2) + ACC_ADDR + be(1, 2) + ACC_KEY + be(DATA.length / 2, 4) + DATA;
  assert.equal(call, callRef);
  assert.equal(roundtrip(mod, 1, call), call);
  // CREATE, no access list
  mod.num('nsw_evm_access_reset');
  setData(mod, INIT);
  const create = enc(mod, 2, { value: '00'.repeat(32), gas: '3000000', nonce: '8' });
  assert.equal(create, '01' + '00'.repeat(32) + be(3000000, 8) + be(8, 8) + be(0, 2) + be(INIT.length / 2, 4) + INIT);
  assert.equal(roundtrip(mod, 2, create), create);
  // the bridge ops: exact lengths 17 / 81 / 137
  setData(mod, '');
  const dep = enc(mod, 3, { amount: '250000000', nonce: '9' });
  assert.equal(dep, '01' + be(250000000, 8) + be(9, 8));
  const wd = enc(mod, 4, { amount: '1', nonce: '10', dest: DEST });
  assert.equal(wd, '01' + be(1, 8) + be(10, 8) + DEST);
  const rd = enc(mod, 5, { amount: '42', dest: DEST, ticket: TICKET });
  assert.equal(rd, '01' + TICKET + be(42, 8) + DEST);
  assert.deepEqual([dep, wd, rd].map(h => h.length / 2), [17, 81, 137]);
  for (const [op, h] of [[3, dep], [4, wd], [5, rd]]) assert.equal(roundtrip(mod, op, h), h);
  assert.equal(enc(mod, 6, {}), '', 'unknown op');
});

test('EVM call bytes: the decoder refuses what the node refuses', { skip }, async () => {
  const mod = await testModule();
  setData(mod, '');
  mod.num('nsw_evm_access_reset');
  const dep = enc(mod, 3, { amount: '5', nonce: '1' });
  assert.equal(roundtrip(mod, 3, dep + '00'), '', 'trailing byte');
  assert.equal(roundtrip(mod, 3, dep.slice(0, -2)), '', 'short');
  assert.equal(roundtrip(mod, 3, '02' + dep.slice(2)), '', 'wrong version');
  assert.equal(roundtrip(mod, 4, dep), '', 'a deposit is not a withdraw');
  setData(mod, DATA);
  const call = enc(mod, 1, { to: TO, value: VALUE, gas: '1', nonce: '1' });
  assert.equal(roundtrip(mod, 1, call + 'ff'), '', 'trailing byte after data');
  // an access list that claims one entry with 2 keys but carries 1
  const head = '01' + TO + VALUE + be(1, 8) + be(1, 8);
  const lying = head + be(1, 2) + ACC_ADDR + be(2, 2) + ACC_KEY + be(0, 4);
  assert.equal(roundtrip(mod, 1, lying), '', 'key count past the data');
  // CREATE initcode: 49 152 bytes pass, 49 153 refuse (EIP-3860)
  const createHead = '01' + '00'.repeat(32) + be(1, 8) + be(1, 8) + be(0, 2);
  const ok = createHead + be(49152, 4) + '00'.repeat(49152);
  assert.equal(roundtrip(mod, 2, ok), ok);
  assert.equal(roundtrip(mod, 2, createHead + be(49153, 4) + '00'.repeat(49153)), '', 'initcode over the cap');
});

const OWNER = 'ab'.repeat(64), SEED32 = '5c'.repeat(32);
const out = (owner, amount, token = '00'.repeat(64)) => Buffer.from(owner, 'ascii').toString('hex') + be(amount, 8) + token + SEED32;
const fund = (role, nuls, outs) => '01' + be(role, 1) + be(nuls.length, 1) + nuls.join('') + be(outs.length, 1) + outs.join('');

test('EVMFUND call (the node\'s layout): round trip and refusals', { skip }, async () => {
  const mod = await testModule();
  const rt = h => mod.str('nsw_test_evmfund_roundtrip', ['string'], [h]);
  const n1 = '11'.repeat(64), n2 = '22'.repeat(64);
  const good = fund(2, [n1, n2], [out(OWNER, 5)]);
  assert.equal(rt(good), good);
  assert.equal(rt(fund(1, [n1], [])), fund(1, [n1], []));
  assert.equal(rt(fund(3, [n1], [])), fund(3, [n1], []));
  assert.equal(rt(fund(0, [n1], [])), '', 'role 0');
  assert.equal(rt(fund(4, [n1], [])), '', 'role 4');
  assert.equal(rt(fund(1, [n2, n1], [])), '', 'inputs not ascending');
  assert.equal(rt(fund(1, [n1, n1], [])), '', 'repeated input');
  assert.equal(rt(fund(1, [], [])), '', 'no input');
  // the node's bound (rtn_xfer_section_parse, RTN_SPEND_MAX_OUT): 0..16
  // change outputs — the former 0..1 was the codec's provisional choice
  const two = fund(1, [n1], [out(OWNER, 1), out(OWNER, 2)]);
  assert.equal(rt(two), two, 'two change outputs');
  const outs16 = Array.from({ length: 16 }, (_, i) => out(OWNER, i + 1));
  assert.equal(rt(fund(1, [n1], outs16)), fund(1, [n1], outs16), 'sixteen change outputs');
  assert.equal(rt(fund(1, [n1], [...outs16, out(OWNER, 17)])), '', 'seventeen change outputs');
  assert.equal(rt(fund(1, [n1], [out(OWNER.toUpperCase(), 1)])), '', 'upper-case owner');
  assert.equal(rt(fund(1, [n1], [out(OWNER, 0)])), '', 'zero amount');
  assert.equal(rt(fund(1, [n1], [out(OWNER, 1, '01'.repeat(64))])), '', 'non-native change');
  assert.equal(rt(good + '00'), '', 'trailing byte');
});

